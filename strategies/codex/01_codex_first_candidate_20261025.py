        positions = getattr(state, 'position', None)
        memory = read_memory(getattr(state, 'traderData', ''))
        saved = memory.get('modules', {})
        if not isinstance(saved, dict): saved = {}
        out_memory = {'version': 1, 'modules': {}, 'risk_diagnostics': []}
        if not isinstance(books, dict) or not isinstance(positions, dict):
            out_memory['risk_diagnostics'].append('invalid_state_mapping')
            return {}, 0, json.dumps(out_memory, separators=(',', ':'))
        orders = {}
        for name in self.active_modules:
            spec = MODULE_SPECS[name]
            text = saved.get(name, '{}')
            if not isinstance(text, str): text = '{}'
            view = SimpleNamespace(
                traderData=text, timestamp=getattr(state, 'timestamp', 0),
                order_depths={p:books[p] for p in spec['data_products'] if p in books},
                position={p:positions[p] for p in spec['data_products'] if p in positions},
                listings=getattr(state, 'listings', {}),
                own_trades=getattr(state, 'own_trades', {}),
                market_trades=getattr(state, 'market_trades', {}),
                observations=getattr(state, 'observations', None))
            try:
                strategy = AMETHYSTMaker(spec['config']) if name == 'A' else VoucherRelativeValue(spec['config'])
                returned = strategy.run(view)
                if not isinstance(returned, tuple) or len(returned) != 3:
                    out_memory['risk_diagnostics'].append(name + ':invalid_module_return')
                    continue
                proposed, conversions, next_text = returned
                if isinstance(next_text, str) and next_text:
                    json.loads(next_text)
            except Exception as exc:
                out_memory['risk_diagnostics'].append(name + ':module_exception:' + type(exc).__name__)
                continue
            if type(conversions) is not int or conversions != 0 or not isinstance(proposed, dict) or not isinstance(next_text, str):
                out_memory['risk_diagnostics'].append(name + ':invalid_module_return')
                continue
            out_memory['modules'][name] = next_text
            for p, rows in proposed.items():
                if p not in spec['traded_products'] or not isinstance(rows, list):
                    out_memory['risk_diagnostics'].append(name + ':ownership_violation')
                    continue
                orders.setdefault(p, []).extend(rows)
        safe = {}
        for p, rows in orders.items():
            position = positions.get(p, 0)
            cap = RISK_CAPS[p]
            if type(position) is not int or abs(position) > LIMITS[p] or top(books.get(p)) is None:
                out_memory['risk_diagnostics'].append(p + ':invalid_position_or_book')
                continue
            buys = max(0, cap-position)
            sells = max(0, cap+position)
            clean = []
            for order in rows:
                if (not isinstance(order, Order) or order.symbol != p or type(order.price) is not int
                    or order.price <= 0 or type(order.quantity) is not int or order.quantity == 0):
                    out_memory['risk_diagnostics'].append(p + ':invalid_order')
                    continue
                amount = min(abs(order.quantity), buys if order.quantity > 0 else sells)
                if amount < abs(order.quantity):
                    out_memory['risk_diagnostics'].append(p + ':risk_clip')
                if amount:
                    clean.append(Order(p, order.price, amount if order.quantity > 0 else -amount))
                    if order.quantity > 0: buys -= amount
                    else: sells -= amount
            bp = [o.price for o in clean if o.quantity > 0]
            ap = [o.price for o in clean if o.quantity < 0]
            if bp and ap and max(bp) >= min(ap):
                out_memory['risk_diagnostics'].append(p + ':self_cross_rejected')
                continue
            if clean: safe[p] = clean
        return safe, 0, json.dumps(out_memory, separators=(',', ':'), allow_nan=False)
