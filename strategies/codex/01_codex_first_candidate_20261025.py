def read_memory(value):
    try:
        obj = json.loads(value) if isinstance(value, str) and value else {}
        return obj if isinstance(obj, dict) else {}
    except (ValueError, TypeError):
        return {}

def top(book):
    try:
        if book is None or not book.buy_orders or (not book.sell_orders):
            return None
        if any((type(p) is not int or p < 0 or type(q) is not int or (q <= 0) for p, q in book.buy_orders.items())):
            return None
        if any((type(p) is not int or p <= 0 or type(q) is not int or (q >= 0) for p, q in book.sell_orders.items())):
            return None
        b, a = (max(book.buy_orders), min(book.sell_orders))
        if b >= a:
            return None
        return (b, a, (b + a) / 2, book.buy_orders[b], -book.sell_orders[a])
    except (AttributeError, TypeError, ValueError, OverflowError):
        return None

def target_orders(symbol, book, position, target, clip=5):
    t = top(book)
    if t is None or type(position) is not int:
        return []
    target = max(-LIMITS[symbol], min(LIMITS[symbol], int(target)))
    diff = target - position
    if diff > 0:
        return [Order(symbol, t[1], min(diff, clip, t[4]))]
    if diff < 0 and t[0] > 0:
        return [Order(symbol, t[0], -min(-diff, clip, t[3]))]
    return []

