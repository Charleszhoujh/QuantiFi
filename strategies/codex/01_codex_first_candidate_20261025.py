    def run(self, state):
        p = 'AMETHYST'
        book = state.order_depths.get(p)
        t = top(book)
        position = state.position.get(p, 0)
        if t is None or type(position) is not int or abs(position) > LIMITS[p]:
            return ({}, 0, '{}')
        c = self.config
        cap = c['position_cap']
        buy_qty = max(0, min(c['order_size'], cap - position))
        sell_qty = max(0, min(c['order_size'], cap + position))
        retreat = abs(position) // c['inventory_step'] if c['inventory_step'] else 0
        bid_ceiling = c['fair_value'] - c['min_edge'] - (retreat if position > 0 else 0)
        ask_floor = c['fair_value'] + c['min_edge'] + (retreat if position < 0 else 0)
