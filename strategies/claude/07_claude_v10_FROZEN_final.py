# TOFFEE_CAKE / JELLY mean reversion: 25 lots fixed-centre model + 25 lots EMA(3000) z>=2 model; best-level execution
# ======================================================================================
def _build_tj(env):
    """Direction N: TOFFEE_CAKE / JELLY mean reversion without a hard-coded mean.

One leg per product (config['legs'][symbol]). Each leg keeps a causal anchor:
  anchor 'fixed'  constant `fair` (control: Codex T40/J80, fair 5000 / 2000)
         'open'   first mid seen today
         'ema'    EMA(mid) with half-life `anchor_hl`, initialised at the first mid
         'mean'   running mean of all mids seen today
The anchor used at tick t is the value BEFORE mid_t is folded in.

Entry threshold:
  entry_mode 'abs'  |mid - anchor| >= entry (price points)
             'z'    |mid - anchor| >= entry * s, s = sqrt(EWMA of dev^2), half-life sd_hl,
                    available after `warmup` ticks
Regime (Codex 'original' rule): enter +/-cap at the threshold, hold until mid
returns to the anchor, then flatten; no re-entry on the tick the book goes flat.
Safeguards (both optional):
  max_hold  ticks in one regime before a forced exit (time stop)
  stop_mult forced exit once |dev| >= stop_mult * threshold (adverse stop)
After a forced exit, that side is blocked until mid crosses back over the anchor.
Execution as the control: limit at the farthest visible opposing level, size = delta.

Only datamodel + standard library.
"""
    import json
    import math

    from datamodel import Order

    LIMITS = {'TOFFEE_CAKE': 50, 'JELLY': 50}
    LEG_DEFAULTS = {'anchor': 'ema', 'fair': None, 'anchor_hl': 3000.0, 'entry_mode': 'abs',
                    'entry': 40.0, 'sd_hl': 1000.0, 'warmup': 300, 'cap': 50,
                    'max_hold': None, 'stop_mult': None}
    DEFAULTS = {'legs': {}}


    def _num(x):
        if isinstance(x, bool) or not isinstance(x, (int, float)):
            return None
        x = float(x)
        return x if math.isfinite(x) else None


    def _int(x, allowed=None, default=0):
        if type(x) is not int or (allowed is not None and x not in allowed):
            return default
        return x


    def _load(raw):
        try:
            obj = json.loads(raw) if isinstance(raw, str) and raw else {}
        except (ValueError, TypeError):
            return {}
        return obj if isinstance(obj, dict) else {}


    def _book(depth):
        try:
            if depth is None or not depth.buy_orders or not depth.sell_orders:
                return None
            bb, ba = max(depth.buy_orders), min(depth.sell_orders)
            if type(bb) is not int or type(ba) is not int or bb >= ba:
                return None
            return bb, ba
        except (AttributeError, TypeError, ValueError):
            return None


    def _exec_level(mode, levels, book):
        """(limit price, max size) for one side; levels sorted best first."""
        vol = [abs(int(book[p])) for p in levels]
        if mode == 'l1':
            return levels[0], vol[0]
        if mode == 'l2':
            k = min(2, len(levels))
            return levels[k - 1], sum(vol[:k])
        return levels[-1], 10 ** 9


    class Trader:
        def __init__(self, config=None):
            cfg = dict(DEFAULTS)
            cfg.update(config or {})
            # Execution (signal untouched). 'sweep' = limit at the farthest visible level for the
            # full size (original); 'l1' = best level only, size capped at its visible volume;
            # 'l2' = up to the second level, size capped at the volume of the first two levels.
            self.exec_entry = cfg.get('exec_entry', 'sweep')
            self.exec_exit = cfg.get('exec_exit', 'sweep')
            self.reserve = cfg.get('reserve', True) is not False
            # legs: {name: leg}; a leg trades leg['product'] (default: its name). Several legs
            # on one product add their targets (a blend of anchor models), one order per product.
            self.legs = {}
            for name, leg in (cfg.get('legs') or {}).items():
                if name in ('_s',):
                    continue
                leg = {**LEG_DEFAULTS, **leg}
                leg.setdefault('product', name)
                if leg['product'] in LIMITS:
                    self.legs[name] = leg

        def run(self, state):
            mem = _load(state.traderData)
            out_mem, targets = {}, {}
            for name, leg in self.legs.items():
                sym = leg['product']
                m = mem.get(name) if isinstance(mem.get(name), dict) else {}
                tob = _book(state.order_depths.get(sym))
                if tob is None:
                    out_mem[name] = m
                    continue
                lp = m.get('p') if type(m.get('p')) is int else 0     # this leg's notional position
                t, m = self._leg(sym, leg, tob, lp, m)
                m['p'] = t
                out_mem[name] = m
                targets[sym] = targets.get(sym, 0) + t
            # Pending reservation (same convention as the Codex portfolio gate): the size
            # submitted last tick on the same side is assumed still working for one more
            # tick, so a delayed fill cannot make us order the same delta twice.
            sent = mem.get('_s') if isinstance(mem.get('_s'), dict) else {}
            new_sent, orders = {}, {}
            for sym, tgt in targets.items():
                depth = state.order_depths.get(sym)
                pos = state.position.get(sym, 0)
                pos = pos if type(pos) is int else 0
                lim = LIMITS[sym]
                last = sent.get(sym) if type(sent.get(sym)) is int else 0
                if not self.reserve:
                    last = 0
                delta = max(-lim, min(lim, tgt)) - pos
                if delta > 0:
                    mode = self.exec_exit if pos < 0 else self.exec_entry      # buying back a short = exit
                    q = min(delta - max(last, 0), lim - pos)
                    lv = sorted(depth.sell_orders)                               # asks, best first
                    px, cap = _exec_level(mode, lv, depth.sell_orders)
                    q = min(q, cap)
                    if q > 0:
                        orders[sym] = [Order(sym, int(px), int(q))]
                        new_sent[sym] = int(q)
                elif delta < 0:
                    mode = self.exec_exit if pos > 0 else self.exec_entry
                    q = min(-delta - max(-last, 0), lim + pos)
                    lv = sorted(depth.buy_orders, reverse=True)                  # bids, best first
                    px, cap = _exec_level(mode, lv, depth.buy_orders)
                    q = min(q, cap)
                    if q > 0:
                        orders[sym] = [Order(sym, int(px), -int(q))]
                        new_sent[sym] = -int(q)
            out_mem['_s'] = new_sent
            return orders, 0, json.dumps(out_mem, separators=(',', ':'))

        @staticmethod
        def _leg(sym, leg, tob, pos, m):
            """Advance one leg; returns (target position of this leg, memory).

        `pos` is the leg's own notional position (its last target), so the exit
        logic works per leg when several legs share one product."""
            bb, ba = tob
            mid = (bb + ba) / 2.0
            n = _int(m.get('n'))
            # ---- anchor (prior value) and its update
            a = _num(m.get('a'))
            kind = leg['anchor']
            if kind == 'fixed':
                anchor = float(leg['fair'])
                a_new = anchor
            else:
                if a is None:
                    a = mid
                anchor = a
                if kind == 'open':
                    a_new = a
                elif kind == 'ema':
                    a_new = a + (1 - 0.5 ** (1 / float(leg['anchor_hl']))) * (mid - a)
                else:                                   # running mean
                    a_new = a + (mid - a) / (n + 1)
            dev = mid - anchor
            v = _num(m.get('v'))
            if leg['entry_mode'] == 'z':
                thr = float(leg['entry']) * math.sqrt(v) if (v is not None and v > 0 and n >= int(leg['warmup'])) else None
            else:
                thr = float(leg['entry'])
            v = dev * dev if v is None else v + (1 - 0.5 ** (1 / float(leg['sd_hl']))) * (dev * dev - v)
            # ---- regime state
            reg = _int(m.get('r'), (-1, 0, 1))
            ex = m.get('x') is True
            blk = _int(m.get('b'), (-1, 0, 1))
            h = _int(m.get('h'))
            if reg == 0 and pos:
                reg, ex = (1 if pos > 0 else -1), True      # unknown inventory: unwind it
            if blk and ((blk > 0 and dev >= 0) or (blk < 0 and dev <= 0)):
                blk = 0                                     # crossed back over the anchor
            flat_now = False
            if ex and pos == 0:
                reg, ex, flat_now, h = 0, False, True, 0
            if reg and not ex:
                h += 1
                if (reg > 0 and dev >= 0) or (reg < 0 and dev <= 0):
                    ex = True
                elif leg['max_hold'] is not None and h > int(leg['max_hold']):
                    ex, blk = True, reg
                elif thr is not None and leg['stop_mult'] is not None and abs(dev) >= float(leg['stop_mult']) * thr:
                    ex, blk = True, reg
            if reg == 0 and not flat_now and thr is not None:
                if dev <= -thr and blk != 1:
                    reg, h = 1, 0
                elif dev >= thr and blk != -1:
                    reg, h = -1, 0
            new_m = {'a': round(a_new, 4), 'v': round(v, 4), 'n': min(n + 1, 10 ** 9),
                     'r': reg, 'x': ex, 'b': blk, 'h': h}
            cap = max(0, min(int(leg['cap']), LIMITS[sym]))
            return (0 if ex else reg * cap), new_m
    return _Namespace(locals())
