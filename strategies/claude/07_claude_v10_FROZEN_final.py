def _build_plugin_basket231(env):
    Order = env['Order']
    LIMITS = env['LIMITS']
    top = env['top']
    read_memory = env['read_memory']
    original = env['original']
    PEARLS = env['PEARLS']
    pending = env['pending']
    target_order = env['target_order']
    detector = env['detector']
    structure = env['structure']
    wave = env['wave']
    claude_I = env['claude_I']
    """Finite causal basket experiments. No redemption or guaranteed simultaneous fills."""
    import copy
    import math

    B='FRUIT_BASKET'
    WEIGHTS={B:1,'DRAGONFRUIT':-2,'GRANADILLA':-3,'MANGOSTEEN':-1}

    def alpha(h): return 1-.5**(1/float(h))

    def signal(mid, quotes, old, c):
        """Current observations may trigger; all fitted estimators are strictly prior."""
        x=sum(WEIGHTS[p]*mid[p] for p in WEIGHTS)
        buy=quotes[B][1]-sum(-WEIGHTS[p]*quotes[p][0] for p in WEIGHTS if p!=B)
        sell=quotes[B][0]-sum(-WEIGHTS[p]*quotes[p][1] for p in WEIGHTS if p!=B)
        mu=old.get('mu',x); v=old.get('v',0.); sd=math.sqrt(max(0.,v))
        n=old.get('n',0); mode=c['mode']; side=old.get('side',0); age=old.get('age',0)
        reason=None; fair=None; values={}; ready=n>=c.get('warmup',500)
        if mode=='mr':
            fair=60. if c.get('fixed') else mu
            if side:
                age+=1; exitfair=old.get('anchor',fair) if c.get('frozen') else fair
                if side*(x-exitfair)>=0: side=0; reason='mean_cross'
                elif age>=1000: side=0; reason='timeout'
            elif ready and sd>0:
                side=1 if buy<fair-2*sd else -1 if sell>fair+2*sd else 0
                if side: age=0
        elif mode=='trend':
            names=[c['own_product']] if c.get('own_product') else [B if c.get('own') else 'basis']
            for p in names:
                value=mid[p] if p!='basis' else x
                hist=old.get('trend',{}).get(p,{})
                diff=hist.get('fast',value)-hist.get('slow',value)
                threshold=(quotes[p][1]-quotes[p][0])/2 if p!='basis' else (buy-sell)/2
                previous=old.get('trend_sides',{}).get(p,0)
                s=previous
                if previous and previous*diff<=0:s=0
                elif not previous and ready:s=1 if diff>threshold else -1 if diff<-threshold else 0
                values[p]={'fast':hist.get('fast',value),'slow':hist.get('slow',value),'diff':diff,'threshold':threshold,'side':s}
            side=values[names[0]]['side']
        elif mode=='lag':
            hist=old.get('history',[])
            if len(hist)>=10:
                previous=hist[-10]
                fair=previous[B]
                if not c.get('own'):fair+=sum(-WEIGHTS[p]*(mid[p]-previous[p]) for p in WEIGHTS if p!=B)
            if side:
                age+=1
                if age>=10:side=0;reason='horizon10'
            elif fair is not None and (not c.get('stale') or old.get('bbo')==list(quotes[B][:2])):
                side=1 if fair>quotes[B][1]+1 else -1 if fair<quotes[B][0]-1 else 0
                if side:age=0
        new=copy.deepcopy(old);new.update(n=n+1,mu=mu+alpha(c.get('hl',500))*(x-mu),v=v+alpha(500)*((x-mu)**2-v),side=side,age=age)
        if side and not old.get('side'):new['anchor']=fair
        new['trend']={}
        for p in list(WEIGHTS)+['basis']:
            value=x if p=='basis' else mid[p];hist=old.get('trend',{}).get(p,{})
            new['trend'][p]={'fast':hist.get('fast',value)+alpha(50)*(value-hist.get('fast',value)),
                             'slow':hist.get('slow',value)+alpha(200)*(value-hist.get('slow',value))}
        new['trend_sides']={p:a['side'] for p,a in values.items()}
        new['history']=(old.get('history',[])+[mid])[-10:];new['bbo']=list(quotes[B][:2])
        targets={p:int(side*c['cap']*w) for p,w in WEIGHTS.items()} if c.get('paired') else {B:int(side*c['cap'])}
        if c.get('own_product'):targets={c['own_product']:int(side*c['cap'])}
        return targets,new,dict(basis=x,buy_basis=buy,sell_basis=sell,prior_mean=mu,prior_sd=sd,fair=fair,prior_n=n,side=side,age=age,exit_reason=reason,trend=values)

    def propose(state,memory,c):
        m=copy.deepcopy(memory)
        if m.get('timestamp')==state.timestamp:return {},m
        quotes={p:top(state.order_depths.get(p)) for p in WEIGHTS}
        if any(x is None for x in quotes.values()):return {},m
        mid={p:v[2] for p,v in quotes.items()}
        desired,new,diag=signal(mid,quotes,m.get('signal',{}),c)
        q={p:state.position.get(p,0) for p in desired};held={p:pending(state,p) for p in desired}
        exiting=m.get('exiting',False);just_flat=False
        flat=not any(q.values()) and not any(any(h) for h in held.values())
        if exiting and flat:exiting=False;just_flat=True
        # One group-level latch handles asynchronous legs, not just a basket fill.
        if not exiting and not just_flat and not flat:
            for p,d in desired.items():
                if (d==0 and (q[p] or any(held[p]))) or q[p]*d<0 or (held[p][0] and d<0 and q[p]>=0) or (held[p][1] and d>0 and q[p]<=0):
                    exiting=True;break
        target={p:0 for p in desired} if exiting or just_flat else dict(desired)
        # Build paired positions in feasible integer groups. Orders are still non-atomic.
        group=m.get('group',0)
        if c.get('paired'):
            if exiting or just_flat:group=0
            else:
                reached=all(q[p]==group*w for p,w in WEIGHTS.items()) and not any(any(h) for h in held.values())
                goal=desired[B]
                if reached and group!=goal:
                    direction=1 if goal>group else -1
                    feasible=min(int((quotes[p][4] if direction*w>0 else quotes[p][3])//abs(w)) for p,w in WEIGHTS.items())
                    group+=direction*min(abs(goal-group),feasible)
                target={p:group*w for p,w in WEIGHTS.items()}
        orders={}
        if not just_flat:
            for p,t in target.items():
                delta=t-q[p]
                if not delta:continue
                quote=quotes[p]
                rows=target_order(state,p,t,quote[1] if delta>0 else quote[0],quote[4] if delta>0 else quote[3])
                if rows:orders[p]=rows
        m.update(timestamp=state.timestamp,signal=new,exiting=exiting,group=group,
                 diagnostic=dict(timestamp=state.timestamp,mid=mid,positions=q,pending=held,desired=desired,target=target,
                                 group=group,exiting=exiting,just_flat=just_flat,orders={p:[[o.price,o.quantity] for o in rows] for p,rows in orders.items()},**diag))
        return orders,m
    return _Namespace(locals())


