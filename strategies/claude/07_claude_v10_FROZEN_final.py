# GOLDEN_PEARLS Avellaneda-Stoikov style passive maker (position clipped to +-10 by the root)
# ======================================================================================
def _build_gp(env):
    """Direction L: passive-quote refinements (user request 2026-10-29).

Modes (config['mode']):
  'flow_passive'  H1: B's stop-and-reverse flow target (EWMA signed tape flow,
                  +-size at |F| >= th), but executed with a one-sided passive
                  quote (penny: best+1 / best-1 when the spread allows, else
                  join) toward the target. After `patience` ticks without
                  reaching the target it crosses the touch (None = never).
  'mm_as'         H2: Avellaneda-Stoikov style maker. Reservation price
                  r = fair - gamma * pos * var - skew * pos / cap (var = EWMA
                  of squared 1-tick mid change) [+ tilt * F]; half-width d = max(min_hw,
                  k_sigma * sqrt(var)). Quotes are clipped to stay passive.
                  fair: 'const' (AMETHYST 10000, official example 3) or EMA(mid).
  'mm_tox'        H3: penny maker with toxicity controls.
                  vpin: |B - S| / (B + S) of EWMA buyer/seller-initiated tape
                  volume; both sides pulled while vpin >= vpin_th.
                  markout: EWMA of our own fills' markout k ticks later
                  (side * (mid_now - fill_px)); both sides pulled for
                  `cooldown` ticks once it falls below mk_th.

Only datamodel + standard library at submission time.
"""
    import json
    import math

    from datamodel import Order

    LIMITS = {'AMETHYST': 50, 'WHITE_PEARLS': 20, 'BLACK_PEARLS': 20, 'GOLDEN_PEARLS': 20,
              'PINK_PEARLS': 20, 'BLUE_PEARLS': 20}
    LIMITS.update({f'VOUCHER_{k}': 50 for k in (6800, 7000, 7200, 7300, 7400, 7500, 7600, 7750, 7900, 8100)})
    FLOW_SET = ('VOUCHER_7300', 'VOUCHER_7400', 'VOUCHER_7500', 'VOUCHER_7600',
                'VOUCHER_7750', 'VOUCHER_7900', 'VOUCHER_8100')
    CONST_FAIR = {'AMETHYST': 10000.0}

    DEFAULTS = {
        'mode': 'flow_passive', 'products': FLOW_SET,
        'half_life': 20, 'th': 3.0, 'size': 10, 'patience': None, 'quote': 'penny',
        'mm_size': 5, 'cap': 20,
        'fair': 'ema', 'fair_hl': 20.0, 'var_hl': 200.0, 'gamma': 0.0, 'k_sigma': 0.0,
        'min_hw': 1.0, 'tilt': 0.0, 'skew': 0.0,
        'vpin_hl': 50.0, 'vpin_th': None, 'vpin_min_vol': 5.0,
        'mk_k': 20, 'mk_hl': 10.0, 'mk_th': None, 'cooldown': 50,
    }


    def _load(raw):
        try:
            m = json.loads(raw) if isinstance(raw, str) and raw else {}
        except (ValueError, TypeError):
            return {}
        return m if isinstance(m, dict) else {}


    def _num(x, default=0.0):
        return x if isinstance(x, (int, float)) and not isinstance(x, bool) and math.isfinite(x) else default


    def _touch(depth):
        try:
            if depth is None or not depth.buy_orders or not depth.sell_orders:
                return None
            bb, ba = max(depth.buy_orders), min(depth.sell_orders)
            bv, av = int(depth.buy_orders[bb]), -int(depth.sell_orders[ba])
            if type(bb) is not int or type(ba) is not int or bb >= ba or bv <= 0 or av <= 0:
                return None
            return bb, bv, ba, av
        except (AttributeError, TypeError, ValueError):
            return None


    def _tape(trades, prev_book, prev_ts, touch):
        """(buyer-initiated units, seller-initiated units) of the visible tape."""
        b = s = 0
        for t in trades or ():
            try:
                px, q = t.price, int(t.quantity)
                if q <= 0 or 'SUBMISSION' in (t.buyer, t.seller):
                    continue
                if prev_book is not None and t.timestamp == prev_ts:
                    if px >= prev_book[1]:
                        b += q
                    elif px <= prev_book[0]:
                        s += q
                elif touch is not None:
                    mid = (touch[0] + touch[2]) / 2
                    if px > mid:
                        b += q
                    elif px < mid:
                        s += q
            except (AttributeError, TypeError, ValueError):
                continue
        return b, s


    class Trader:
        def __init__(self, config=None):
            self.cfg = {**DEFAULTS, **(config or {})}

        def run(self, state):
            cfg = self.cfg
            mem = _load(getattr(state, 'traderData', ''))
            P = mem.get('p') if isinstance(mem.get('p'), dict) else {}
            prev_ts = mem.get('t')
            ts = getattr(state, 'timestamp', 0)
            steps = 1
            if isinstance(prev_ts, int) and isinstance(ts, int) and ts > prev_ts:
                steps = max(1, (ts - prev_ts) // 100)
            depths = getattr(state, 'order_depths', {}) or {}
            market = getattr(state, 'market_trades', {}) or {}
            own = getattr(state, 'own_trades', {}) or {}
            positions = getattr(state, 'position', {}) or {}
            orders, newP = {}, {}
            for p in cfg['products']:
                if p not in LIMITS:
                    continue
                m = P.get(p) if isinstance(P.get(p), dict) else {}
                touch = _touch(depths.get(p))
                pb = m.get('bk')
                prev_book = tuple(pb) if (isinstance(pb, list) and len(pb) == 2
                                          and all(type(v) is int for v in pb)) else None
                buy_u, sell_u = _tape(market.get(p), prev_book, prev_ts, touch)
                dec = 0.5 ** (steps / max(1e-9, float(cfg['half_life'])))
                f = _num(m.get('f')) * dec + buy_u - sell_u
                vd = 0.5 ** (steps / max(1e-9, float(cfg['vpin_hl'])))
                vb = _num(m.get('vb')) * vd + buy_u
                vs = _num(m.get('vs')) * vd + sell_u
                nm = {'f': round(f, 4), 'vb': round(vb, 4), 'vs': round(vs, 4)}
                if touch is None:
                    newP[p] = {**m, **nm}
                    continue
                bb, bv, ba, av = touch
                mid = (bb + ba) / 2.0
                nm['bk'] = [bb, ba]
                pos = positions.get(p, 0)
                pos = pos if type(pos) is int else 0
                lim = LIMITS[p]
                # variance of 1-tick mid change and fair EMA
                pm = m.get('m')
                var = _num(m.get('v'), None)
                if isinstance(pm, (int, float)) and not isinstance(pm, bool):
                    dm = mid - pm
                    a = 1 - 0.5 ** (1 / float(cfg['var_hl']))
                    var = dm * dm if var is None else var + a * (dm * dm - var)
                nm['m'] = mid
                if var is not None:
                    nm['v'] = round(var, 6)
                fe = _num(m.get('fe'), None)
                fe = mid if fe is None else fe + (1 - 0.5 ** (1 / float(cfg['fair_hl']))) * (mid - fe)
                nm['fe'] = round(fe, 4)
                out = []
                mode = cfg['mode']
                if mode == 'flow_passive':
                    out, nm = self._flow_passive(p, cfg, m, nm, f, bb, bv, ba, av, pos, lim)
                elif mode == 'mm_as':
                    fair = CONST_FAIR.get(p, fe) if cfg['fair'] == 'const' else fe
                    out = self._mm_as(p, cfg, fair, var, f, bb, ba, pos, lim)
                elif mode == 'mm_tox':
                    out, nm = self._mm_tox(p, cfg, m, nm, own.get(p), ts, mid, vb, vs, bb, ba, pos, lim)
                newP[p] = nm
                if out:
                    orders[p] = out
            mem = {'p': newP, 't': ts if isinstance(ts, int) else None}
            return orders, 0, json.dumps(mem, separators=(',', ':'))

        # ---------------------------------------------------------------- H1
        @staticmethod
        def _flow_passive(p, cfg, m, nm, f, bb, bv, ba, av, pos, lim):
            size = max(0, min(int(cfg['size']), lim))
            g = m.get('g') if type(m.get('g')) is int else 0
            if f >= cfg['th']:
                g = size
            elif f <= -cfg['th']:
                g = -size
            g = max(-size, min(size, g))
            w = m.get('w') if type(m.get('w')) is int else 0
            diff = g - pos
            w = w + 1 if diff != 0 else 0
            nm.update(g=g, w=w)
            if diff == 0:
                return [], nm
            pat = cfg['patience']
            cross = pat is not None and w > int(pat)
            pen = cfg['quote'] == 'penny' and ba - bb >= 2
            if diff > 0:
                if cross:
                    q = min(diff, av, lim - pos)
                    return ([Order(p, ba, int(q))] if q > 0 else []), nm
                px = bb + 1 if pen else bb
                q = min(diff, lim - pos)
                return ([Order(p, int(px), int(q))] if q > 0 else []), nm
            if cross:
                q = min(-diff, bv, lim + pos)
                return ([Order(p, bb, -int(q))] if q > 0 else []), nm
            px = ba - 1 if pen else ba
            q = min(-diff, lim + pos)
            return ([Order(p, int(px), -int(q))] if q > 0 else []), nm

        # ---------------------------------------------------------------- H2
        @staticmethod
        def _mm_as(p, cfg, fair, var, f, bb, ba, pos, lim):
            if var is None:
                return []
            sd = math.sqrt(max(var, 0.0))
            cap = max(1, min(int(cfg['cap']), lim))
            r = (fair - float(cfg['gamma']) * pos * var - float(cfg['skew']) * pos / cap
                 + float(cfg['tilt']) * f)
            hw = max(float(cfg['min_hw']), float(cfg['k_sigma']) * sd)
            bid_px = min(math.floor(r - hw), ba - 1)
            ask_px = max(math.ceil(r + hw), bb + 1)
            cap = max(0, min(int(cfg['cap']), lim))
            qb = min(int(cfg['mm_size']), cap - pos)
            qa = min(int(cfg['mm_size']), cap + pos)
            out = []
            if bid_px >= ask_px:
                return out
            if qb > 0 and bid_px > 0:
                out.append(Order(p, int(bid_px), int(qb)))
            if qa > 0:
                out.append(Order(p, int(ask_px), -int(qa)))
            return out

        # ---------------------------------------------------------------- H3
        @staticmethod
        def _mm_tox(p, cfg, m, nm, own_tr, ts, mid, vb, vs, bb, ba, pos, lim):
            # own fills -> pending markout queue [(ts, side, px)]
            q = m.get('q') if isinstance(m.get('q'), list) else []
            q = [x for x in q if isinstance(x, list) and len(x) == 3 and all(isinstance(v, (int, float)) for v in x)]
            for t in own_tr or ():
                try:
                    side = 1 if t.buyer == 'SUBMISSION' else (-1 if t.seller == 'SUBMISSION' else 0)
                    if side:
                        q.append([int(t.timestamp), side * int(t.quantity), float(t.price)])
                except (AttributeError, TypeError, ValueError):
                    continue
            mk = _num(m.get('mk'), None)
            k = int(cfg['mk_k']) * 100
            keep = []
            a = 1 - 0.5 ** (1 / float(cfg['mk_hl']))
            for t0, sq, px in q:
                if isinstance(ts, int) and ts - t0 >= k:
                    per = (1 if sq > 0 else -1) * (mid - px)
                    mk = per if mk is None else mk + a * (per - mk)
                else:
                    keep.append([t0, sq, px])
            nm['q'] = keep[-30:]
            if mk is not None:
                nm['mk'] = round(mk, 4)
            cd = m.get('cd') if type(m.get('cd')) is int else 0
            cd = max(0, cd - 1)
            if cfg['mk_th'] is not None and mk is not None and mk < float(cfg['mk_th']) and cd == 0:
                cd = int(cfg['cooldown'])
                nm['mk'] = 0.0                       # restart the estimate after a pause
            nm['cd'] = cd
            toxic = cd > 0
            if cfg['vpin_th'] is not None and vb + vs >= float(cfg['vpin_min_vol']):
                if abs(vb - vs) / (vb + vs) >= float(cfg['vpin_th']):
                    toxic = True
            if toxic:
                return [], nm
            cap = max(0, min(int(cfg['cap']), lim))
            if cfg['quote'] == 'penny' and ba - bb >= 3:
                bid_px, ask_px = bb + 1, ba - 1
            else:
                bid_px, ask_px = bb, ba
            qb = min(int(cfg['mm_size']), cap - pos)
            qa = min(int(cfg['mm_size']), cap + pos)
            out = []
            if qb > 0 and bid_px < ask_px:
                out.append(Order(p, int(bid_px), int(qb)))
            if qa > 0 and bid_px < ask_px:
                out.append(Order(p, int(ask_px), -int(qa)))
            return out, nm
    return _Namespace(locals())
