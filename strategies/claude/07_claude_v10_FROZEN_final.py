# Causal swing-pivot detector (confirmed highs/lows) used by the TELLURIUM breakout
# ======================================================================================
def _build_detector(env):
    """Causal directional-change detector. Standard library only; no trading.

An extreme is a historical observation. It becomes available as a confirmed
pivot only after the fixed reversal distance is observed. Confirmed events are
never revised. Unconfirmed extrema are stored separately and must not be used
as if their future confirmation were known.
"""
    from copy import deepcopy
    import math

    VERSION = 1
    HISTORY_LIMIT = 12


    def _price(value):
        return type(value) in (int, float) and math.isfinite(value) and value > 0


    def _index(value):
        return type(value) is int and value >= 0


    def _point(price, index, timestamp):
        return {'price': float(price), 'index': index, 'timestamp': timestamp}


    def _valid_point(point):
        return (isinstance(point, dict) and _price(point.get('price'))
                and _index(point.get('index')) and _index(point.get('timestamp')))


    def _validate(memory, threshold):
        """Reject malformed state rather than silently inventing missing history."""
        if not isinstance(memory, dict) or memory.get('version') != VERSION:
            raise ValueError('invalid detector memory version')
        if memory.get('threshold') != threshold:
            raise ValueError('threshold changed within detector history')
        if type(memory.get('direction')) is not int or memory['direction'] not in (-1,0,1):
            raise ValueError('invalid detector direction')
        if not _valid_point(memory.get('last')) or not _index(memory.get('sequence')):
            raise ValueError('invalid last observation or sequence')
        pivots=memory.get('pivots')
        if not isinstance(pivots, list) or len(pivots)>HISTORY_LIMIT:
            raise ValueError('invalid pivot history')
        previous=None
        for p in pivots:
            if (not isinstance(p, dict) or type(p.get('id')) is not int or p['id']<=0
                or p.get('kind') not in ('H','L') or not _price(p.get('price'))
                or not _price(p.get('confirmation_price')) or p.get('threshold')!=threshold
                or not all(_index(p.get(k)) for k in ('extreme_index','extreme_timestamp','confirmation_index','confirmation_timestamp'))
                or p['extreme_index']>=p['confirmation_index']
                or p['extreme_timestamp']>=p['confirmation_timestamp']
                or p['confirmation_index']>memory['last']['index']
                or p['confirmation_timestamp']>memory['last']['timestamp']):
                raise ValueError('invalid confirmed pivot')
            if previous is not None and (p['id']!=previous['id']+1 or p['kind']==previous['kind']
                or p['extreme_index']<=previous['extreme_index']
                or p['confirmation_index']<=previous['confirmation_index']):
                raise ValueError('invalid pivot ordering')
            signed=(p['confirmation_price']-p['price'])*(1 if p['kind']=='L' else -1)
            if signed<threshold:raise ValueError('pivot reversal below threshold')
            previous=p
        if pivots and pivots[-1]['id']!=memory['sequence']:
            raise ValueError('pivot sequence mismatch')
        if memory['direction']==0:
            if pivots or memory['sequence'] or memory.get('extreme') is not None:
                raise ValueError('uninitialized direction has confirmed history')
            if not _valid_point(memory.get('initial_low')) or not _valid_point(memory.get('initial_high')):
                raise ValueError('invalid initial extrema')
            if not memory['initial_low']['price']<=memory['last']['price']<=memory['initial_high']['price']:
                raise ValueError('last observation outside initial extrema')
            if any(memory[k]['index']>memory['last']['index'] or memory[k]['timestamp']>memory['last']['timestamp'] for k in ('initial_low','initial_high')):
                raise ValueError('initial extreme contains a future observation')
            if memory['initial_high']['price']-memory['initial_low']['price']>=threshold:
                raise ValueError('unconfirmed initial range already crosses threshold')
        else:
            if not pivots or not _valid_point(memory.get('extreme')):
                raise ValueError('missing confirmed anchor or running extreme')
            if pivots[-1]['kind'] != ('L' if memory['direction']==1 else 'H'):
                raise ValueError('direction and confirmed anchor disagree')
            if memory['extreme']['index']<pivots[-1]['confirmation_index']:
                raise ValueError('running extreme predates last confirmation')
            if (memory['extreme']['index']>memory['last']['index']
                or memory['extreme']['timestamp']>memory['last']['timestamp']
                or memory['extreme']['timestamp']<pivots[-1]['confirmation_timestamp']):
                raise ValueError('invalid running extreme chronology')
            distance=memory['direction']*(memory['extreme']['price']-memory['last']['price'])
            if not 0<=distance<threshold:
                raise ValueError('unconfirmed running extreme is inconsistent with last price')


    def step(mid, index, timestamp, memory, threshold):
        """Return ``(new_memory, newly_confirmed_event_or_None)``.

    ``index`` is an observation index, not elapsed time. Timestamp is preserved
    without assuming its units. A repeated already-processed observation is
    idempotent and emits no second event. New observations must increase both.
    A caller can record all returned events; memory retains only the last12.
    Input memory and prior event dictionaries are never mutated.
    """
        if not _price(mid):raise ValueError('mid must be finite and positive')
        if not _index(index) or not _index(timestamp):raise ValueError('index/timestamp must be nonnegative integers')
        if not _price(threshold):raise ValueError('threshold must be finite and positive')
        threshold=float(threshold);point=_point(mid,index,timestamp)
        if memory is None or memory=={}:
            return {'version':VERSION,'threshold':threshold,'direction':0,
                    'sequence':0,'pivots':[],'last':point,
                    'initial_low':dict(point),'initial_high':dict(point),'extreme':None},None
        _validate(memory,threshold)
        last=memory['last']
        if index==last['index'] and timestamp==last['timestamp'] and float(mid)==last['price']:
            return deepcopy(memory),None
        if index<=last['index'] or timestamp<=last['timestamp']:
            raise ValueError('conflicting duplicate or nonmonotone observation')
        m=deepcopy(memory);event=None;direction=m['direction']

        def confirm(extreme,kind,new_direction):
            nonlocal event
            m['sequence']+=1
            event={'id':m['sequence'],'kind':kind,'price':extreme['price'],
                   'extreme_index':extreme['index'],'extreme_timestamp':extreme['timestamp'],
                   'confirmation_index':index,'confirmation_timestamp':timestamp,
                   'confirmation_price':float(mid),'threshold':threshold}
            m['pivots']=(m['pivots']+[deepcopy(event)])[-HISTORY_LIMIT:]
            m['direction']=new_direction;m['extreme']=dict(point)
            m['initial_low']=None;m['initial_high']=None

        if direction==0:
            if mid<m['initial_low']['price']:m['initial_low']=dict(point)
            if mid>m['initial_high']['price']:m['initial_high']=dict(point)
            if mid-m['initial_low']['price']>=threshold:
                confirm(m['initial_low'],'L',1)
            elif m['initial_high']['price']-mid>=threshold:
                confirm(m['initial_high'],'H',-1)
        elif direction==1:
            if mid>m['extreme']['price']:m['extreme']=dict(point)
            elif m['extreme']['price']-mid>=threshold:
                confirm(m['extreme'],'H',-1)
        else:
            if mid<m['extreme']['price']:m['extreme']=dict(point)
            elif mid-m['extreme']['price']>=threshold:
                confirm(m['extreme'],'L',1)
        m['last']=point
        return m,deepcopy(event)
    return _Namespace(locals())


# ======================================================================================
# Rules on confirmed pivots (breakout / wave-3 / five-wave setups) used by the TELLURIUM breakout
# ======================================================================================
def _build_structure(env):
    """Narrow, auditable Elliott-style rules on *confirmed* causal pivots.

This module does not detect pivots, observe current quotes, place orders, choose
parameters or backdate entries. `available_index` is the earliest possible
decision index, not a traded extreme. The default caller must supply only the
confirmed pivots available now; asof_index adds an explicit availability check.
"""
    import math

    MODES = ('swingbreak', 'wave3', 'fiveabc')
    NEEDED = {'swingbreak': 2, 'wave3': 3, 'fiveabc': 9}
    FIB_W2 = (0.382, 0.786)
    FIB_W4 = (0.236, 0.5)
    FIB_ABC = (0.382, 0.786)


    def _number(x):
        return type(x) in (int, float) and math.isfinite(x)


    def _validate(pivots, asof_index=None):
        if not isinstance(pivots, (list, tuple)):
            return 'pivots_not_sequence'
        if asof_index is not None and (type(asof_index) is not int or asof_index < 0):
            return 'invalid_asof_index'
        previous = None
        for p in pivots:
            if not isinstance(p, dict):
                return 'pivot_not_dict'
            if type(p.get('id')) is not int or p['id'] < 1:
                return 'invalid_pivot_id'
            if p.get('kind') not in ('H', 'L'):
                return 'invalid_pivot_kind'
            if not _number(p.get('price')) or p['price'] <= 0:
                return 'invalid_pivot_price'
            for k in ('extreme_index', 'extreme_timestamp', 'confirmation_index', 'confirmation_timestamp'):
                if type(p.get(k)) is not int or p[k] < 0:
                    return 'invalid_pivot_coordinate'
            if p['extreme_index'] >= p['confirmation_index']:
                return 'confirmation_not_after_extreme'
            if p['extreme_timestamp'] >= p['confirmation_timestamp']:
                return 'confirmation_time_not_after_extreme'
            if asof_index is not None and p['confirmation_index'] > asof_index:
                return 'future_confirmation'
            if previous is not None:
                if p['id'] <= previous['id']:
                    return 'nonincreasing_pivot_id'
                if p['kind'] == previous['kind']:
                    return 'nonalternating_pivots'
                if (p['extreme_index'] <= previous['extreme_index'] or
                    p['confirmation_index'] <= previous['confirmation_index'] or
                    p['extreme_timestamp'] <= previous['extreme_timestamp'] or
                    p['confirmation_timestamp'] <= previous['confirmation_timestamp']):
                    return 'nonincreasing_pivot_coordinate'
                if (p['kind'] == 'H' and p['price'] <= previous['price']) or (p['kind'] == 'L' and p['price'] >= previous['price']):
                    return 'nonpositive_swing_length'
            previous = p
        return None


    def _side(pivots):
        return 1 if pivots[-1]['kind'] == 'L' else -1


    def _impulse(prices):
        """Prices transformed by desired side, so every test is bullish."""
        if len(prices) != 6:
            return False, 'need_six_impulse_pivots', {}
        a, b, c, d, e, f = prices
        w1, w3, w5 = b-a, d-c, f-e
        ratios = {'wave1_length': w1, 'wave3_length': w3, 'wave5_length': w5,
                  'wave2_retracement': (b-c)/w1,
                  'wave4_retracement': (d-e)/w3}
        for ok, reason in ((c > a, 'wave2_beyond_or_equal_start'),
                           (d > b, 'wave3_does_not_extend_wave1'),
                           (e > b, 'wave4_overlaps_wave1'),
                           (f > d, 'wave5_does_not_extend_wave3'),
                           (w3 >= min(w1, w5), 'wave3_is_shortest')):
            if not ok:
                return False, reason, ratios
        return True, 'impulse_valid', ratios


    def impulse(pivots, asof_index=None):
        """Latest six pivots: completed five-wave count, separate from ABC."""
        if not isinstance(pivots, (list, tuple)) or len(pivots) < 6:
            return {'valid': False, 'reason': 'insufficient_impulse_pivots', 'ratios': {}}
        tail = pivots[-6:]
        error = _validate(tail, asof_index)
        if error:
            return {'valid': False, 'reason': error, 'ratios': {}}
        # A long impulse ends at H; a short one ends at L.
        side = 1 if tail[0]['kind'] == 'L' else -1
        ok, reason, ratios = _impulse([side*p['price'] for p in tail])
        return {'valid': ok, 'reason': reason, 'side': side, 'ratios': ratios,
                'pivot_ids': [p['id'] for p in tail],
                'available_index': tail[-1]['confirmation_index'],
                'available_timestamp': tail[-1]['confirmation_timestamp']}


    def _pack(tail, mode, fib, side, breakout, stop, ratios, labels):
        legs = []
        for i, (start, end) in enumerate(zip(tail, tail[1:])):
            legs.append({'label': labels[i+1], 'start_pivot_id': start['id'],
                         'end_pivot_id': end['id'],
                         'start_extreme_index': start['extreme_index'],
                         'end_extreme_index': end['extreme_index'],
                         'start_price': start['price'], 'end_price': end['price'],
                         'absolute_length': abs(end['price']-start['price']),
                         'available_index': end['confirmation_index']})
        ident = mode+(':fib' if fib else ':plain')+':'+str(side)+':'+'-'.join(
            str(p['id'])+'@'+str(p['confirmation_index']) for p in tail)
        return {'setup_id': ident, 'mode': mode, 'fib': fib, 'side': side,
                'breakout': breakout, 'stop': stop,
                'available_index': tail[-1]['confirmation_index'],
                'available_timestamp': tail[-1]['confirmation_timestamp'],
                'pivot_ids': [p['id'] for p in tail],
                'wave_ids': dict(zip(labels, [p['id'] for p in tail])),
                'legs': legs, 'ratios': ratios}


    def inspect(pivots, mode, fib=False, asof_index=None):
        """Return eligibility and rejection reason without observing future prices.

    `impulse_valid` and `abc_valid` are separately countable diagnostics for
    full-five-plus-ABC candidates. No valid setup implies any guaranteed fill.
    """
        if mode not in MODES:
            raise ValueError('unknown structure mode')
        if type(fib) is not bool:
            raise ValueError('fib must be bool')
        if mode == 'swingbreak' and fib:
            raise ValueError('two-pivot swingbreak has no impulse Fibonacci denominator')
        result = {'valid': False, 'reason': 'insufficient_pivots', 'setup': None,
                  'impulse_valid': False, 'abc_valid': False, 'ratios': {}}
        if not isinstance(pivots, (list, tuple)) or len(pivots) < NEEDED[mode]:
            return result
        tail = pivots[-NEEDED[mode]:]
        error = _validate(tail, asof_index)
        if error:
            result['reason'] = error
            return result
        side = _side(tail)
        prices = [side*p['price'] for p in tail]
        ratios = {}
        if mode == 'swingbreak':
            breakout = tail[0]['price']; labels = ('prior_extreme', 'pullback')
        elif mode == 'wave3':
            a, b, c = prices
            ratios = {'wave1_length': b-a, 'wave2_retracement': (b-c)/(b-a)}
            result['ratios'] = ratios
            if not c > a:
                result['reason'] = 'wave2_beyond_or_equal_start'
                return result
            if fib and not FIB_W2[0] <= ratios['wave2_retracement'] <= FIB_W2[1]:
                result['reason'] = 'fib_wave2_outside_band'
                return result
            breakout = tail[1]['price']; labels = ('W0', 'W1', 'W2')
        else:
            ok, reason, ratios = _impulse(prices[:6])
            result['ratios'] = ratios
            result['impulse_valid'] = ok
            if not ok:
                result['reason'] = reason
                return result
            if not prices[7] < prices[5]:
                result['reason'] = 'B_not_below_wave5'
                return result
            if not prices[8] < prices[6]:
                result['reason'] = 'C_not_beyond_A'
                return result
            result['abc_valid'] = True
            ratios['abc_retracement'] = (prices[5]-prices[8])/(prices[5]-prices[0])
            for name, bounds in (('wave2_retracement', FIB_W2),
                                 ('wave4_retracement', FIB_W4),
                                 ('abc_retracement', FIB_ABC)):
                if fib and not bounds[0] <= ratios[name] <= bounds[1]:
                    result['reason'] = 'fib_'+name+'_outside_band'
                    return result
            breakout = tail[7]['price']; labels = ('W0', 'W1', 'W2', 'W3', 'W4', 'W5', 'A', 'B', 'C')
        result['valid'] = True
        result['reason'] = 'eligible'
        result['ratios'] = ratios
        result['setup'] = _pack(tail, mode, fib, side, breakout, tail[-1]['price'], ratios, labels)
        return result


    def setup(pivots, mode, fib=False, asof_index=None):
        """Return a current eligible setup or None; never emits an order."""
        return inspect(pivots, mode, fib, asof_index)['setup']
    return _Namespace(locals())
detector = _build_detector({})
structure = _build_structure({})
_COMMON.update(detector=detector, structure=structure)


