def _build_helpers(env):
    Order = env['Order']
    LIMITS = env['LIMITS']
    top = env['top']
    read_memory = env['read_memory']
    original = env['original']
    """Small causal order helpers. Pending amount is prior submitted worst-side size."""

    PEARLS=('BLACK_PEARLS','BLUE_PEARLS','GOLDEN_PEARLS','PINK_PEARLS','WHITE_PEARLS')

    def pending(state, product):
        v=getattr(state,'pending_orders',{}).get(product,(0,0))
        if not isinstance(v,(tuple,list)) or len(v)!=2 or any(type(x) is not int or x<0 for x in v):
            return (40,40)
        return tuple(v)

    def target_order(state, product, target, price, clip=None):
        q=state.position.get(product,0); delta=target-q
        if not delta: return []
        side=1 if delta>0 else -1
        n=max(0,abs(delta)-pending(state,product)[0 if side>0 else 1])
        if clip is not None: n=min(n,clip)
        return [Order(product,int(price),side*n)] if n else []
    return _Namespace(locals())
_helpers = _build_helpers(dict(_COMMON))
_COMMON.update({k: getattr(_helpers, k) for k in ('PEARLS', 'pending', 'target_order')})


