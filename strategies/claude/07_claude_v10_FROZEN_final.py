    def _orders_to_target(book, view, position, target, config, feature, entry):
        """Price actual visible levels; engine alone decides whether they fill.

    Fair gate estimates future liquidation at fitted level + horizon*slope,
    minus current halfspread for a long (plus for a short). It is a forecast,
    not a promise of future liquidity. Depth is used only for entry.
    """
        diff=target-position
        if not diff:return []
        direction=sign(diff);budget=min(abs(diff),config['clip']);rows=[]
        prices=sorted(book.sell_orders) if direction>0 else sorted(book.buy_orders,reverse=True)
        if not (entry and config['entry_depth']):prices=prices[:1]
        forecast=None
        if entry and config['fair_gate']:
            forecast=feature['fitted_now']+config['forecast_horizon']*feature['slope']
        for px in prices:
            if forecast is not None and direction*(forecast-px)<=view['spread']/2:
                break
            depth=-book.sell_orders[px] if direction>0 else book.buy_orders[px]
            amount=min(budget,depth)
            if amount:rows.append(Order(PRODUCT,int(px),direction*int(amount)));budget-=amount
            if not budget:break
        return rows


    def propose(state, memory, config):
        """Return proposed orders and per-module JSON-compatible memory.

    No pending capacity is reserved here. The root portfolio controller owns
    aggregate per-product reservation and arbitration. Gap4 also prevents this
    module from submitting duplicate delayed reductions in the tested latency1
    model. Other order lifetimes/delays remain unverified.
    """
        c=_valid_config(config)
        if c['mode']=='legacy':
            if c['cap']!=1:raise ValueError('legacy baseline fixed at1')
            legacy=LegacyTrader(dict(DEFAULT,policy='hysteresis'))
            # All observation data remain the same; only this module's traderData
            # is isolated from the parent portfolio JSON namespace.
            local=SimpleNamespace(**vars(state))
            local.traderData=json.dumps(memory,separators=(',',':')) if memory else ''
            orders,conversions,raw=legacy.run(local)
            assert conversions==0
            return orders,json.loads(raw)

        m,corrupt=_memory_v2(memory);m['n']+=1;n=m['n'];ts=getattr(state,'timestamp',None)
        previous_ts=m['last_ts'];valid_ts=natural(ts)
        continuous=valid_ts and (previous_ts is None or ts-previous_ts==100)
        m['last_ts']=ts if valid_ts else None
        books=getattr(state,'order_depths',{})
        book=books.get(PRODUCT) if isinstance(books,dict) else None
        v=book_view(book)
        if not continuous or v is None:m['prices']=[]
        if v is not None:m['prices']=(m['prices']+[v['mid']])[-60:]
        ready=v is not None and len(m['prices'])>=c['window']
        beta=slope(m['prices'][-c['window']:]) if ready else None
        tail=m['prices'][-c['window']:]
        fitted_now=(sum(tail)/len(tail)+beta*(len(tail)-1)/2) if ready else None
        feature={'slope':beta,'fitted_now':fitted_now,'ready':ready}
        m['last_feature']=feature
        positions=getattr(state,'position',{})
        q=positions.get(PRODUCT,0) if isinstance(positions,dict) else None
        if type(q) is not int or abs(q)>50:return {},m
        e=m['event'];cleanup=False
        if q and (e is None or q*e['side']<0):
            e={'side':sign(q),'phase':'exit','seen_fill':True};m['event']=e
            m['quarantine_until']=max(m['quarantine_until'],n+4)

        def send(target,entry):
            if v is None or n<m['next_send'] or n<m['quarantine_until']:return {}
            rows=_orders_to_target(book,v,q,target,c,feature,entry)
            if rows:
                m['next_send']=n+c['order_gap']
                return {PRODUCT:rows}
            return {}

        if e is not None:
            if q:
                e['seen_fill']=True
                if e['phase']!='exit':e['phase']='holding'
            if (corrupt or not continuous or v is None or not ready or abs(q)>c['cap']
                or (beta is not None and e['side']*beta<=c['exit'])):
                e['phase']='exit'
            if q:
                if e['phase']=='exit':return send(0,False),m
                # Stage into the target only while the original entry criterion
                # remains true. The middle hysteresis region holds existing units.
                if e['side']*beta>c['entry'] and abs(q)<c['cap']:
                    return send(e['side']*c['cap'],True),m
                return {},m
            if e['seen_fill'] or n>=m['next_send']:
                m['event']=None;e=None;cleanup=True
            else:return {},m
        side=sign(beta) if ready and abs(beta)>c['entry'] else 0
        if (side and continuous and not cleanup and n>=m['next_send'] and n>=m['quarantine_until']):
            e={'side':side,'phase':'entry','seen_fill':False};m['event']=e
            orders=send(side*c['cap'],True)
            if not orders:m['event']=None
            return orders,m
        return {},m
    return _Namespace(locals())


