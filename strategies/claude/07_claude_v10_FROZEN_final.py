_TD_ENC = {k: '~' + format(i, 'x') for i, k in enumerate(_TD_KEYS)}

_TD_DEC = {v: k for k, v in _TD_ENC.items()}

def _td_keys(o, table):
    if isinstance(o, dict):
        return {table.get(k, k): _td_keys(v, table) for k, v in o.items()}
    if isinstance(o, list):
        return [_td_keys(v, table) for v in o]
    return o

def _td_obj(s):
    if isinstance(s, str) and s:
        try:
            return {'~j': json.loads(s)}
        except (ValueError, TypeError):
            return s
    return s

def _td_str(v):
    if isinstance(v, dict) and set(v) == {'~j'}:
        return json.dumps(v['~j'], separators=(',', ':'))
    return v

def _td_pack(out):
    c = _td_obj(out.get('c'))
    if isinstance(c, dict) and isinstance(c['~j'], dict) and isinstance(c['~j'].get('modules'), dict):
        mods = {}
        for name, text in c['~j']['modules'].items():
            o = _td_obj(text)
            if isinstance(o, dict) and set(o) == {'~j'} and isinstance(o['~j'], dict):
                o = {'~j': {k: v for k, v in o['~j'].items() if k != 'diagnostic'}}
            elif isinstance(o, dict):                # memory already stored as an object
                o = {k: v for k, v in o.items() if k != 'diagnostic'}
            mods[name] = o
        c = {'~j': dict(c['~j'], modules=mods)}
    packed = {'~v': 2, 'c': c, 'n': _td_obj(out.get('n')), 'k': out.get('k'), 'g': _td_obj(out.get('g')), '_ts': out.get('_ts')}
    return json.dumps(_td_keys(packed, _TD_ENC), separators=(',', ':'))

def _td_unpack(raw):
    try:
        obj = json.loads(raw) if raw else {}
    except (ValueError, TypeError):
        return {}
    if not isinstance(obj, dict) or obj.get('~v') != 2:
        return obj                                   # legacy (v7) format or empty
    obj = _td_keys(obj, _TD_DEC)
    c = obj.get('c')
    if isinstance(c, dict) and set(c) == {'~j'} and isinstance(c['~j'], dict) and isinstance(c['~j'].get('modules'), dict):
        c = {'~j': dict(c['~j'], modules={k: _td_str(v) for k, v in c['~j']['modules'].items()})}
    return {'c': _td_str(c), 'n': _td_str(obj.get('n')), 'k': obj.get('k'), 'g': _td_str(obj.get('g')), '_ts': obj.get('_ts')}


