# Shared order/book helpers + AMETHYST maker + option pricing (Black-Scholes, implied variance, smile fits)
# ======================================================================================
def _build_original(env):
    """QuantiFi 2026 local research candidate: APPROXIMATE replay only.
Generated by tools/build_submission.py; no private data or file access.
Rename to your official Team##QuantiFi2026.py only when preparing submission.
No submission, login, or official backtest has been performed.
"""
    import json
    import math
    from types import SimpleNamespace
    from datamodel import Order

    LIMITS = {'AMETHYST': 50, 'TOFFEE_CAKE': 50, 'PAPER_LANTERNS': 50, 'TELLURIUM': 40, 'JELLY': 50, 'PEANUT_BUTTER': 50, 'DRAGONFRUIT': 40, 'GRANADILLA': 40, 'MANGOSTEEN': 40, 'FRUIT_BASKET': 40, 'LYCHEE': 200, 'WHITE_PEARLS': 20, 'BLACK_PEARLS': 20, 'GOLDEN_PEARLS': 20, 'PINK_PEARLS': 20, 'BLUE_PEARLS': 20, 'VOUCHER_6800': 50, 'VOUCHER_7000': 50, 'VOUCHER_7200': 50, 'VOUCHER_7300': 50, 'VOUCHER_7400': 50, 'VOUCHER_7500': 50, 'VOUCHER_7600': 50, 'VOUCHER_7750': 50, 'VOUCHER_7900': 50, 'VOUCHER_8100': 50}

    def read_memory(value):
        try:
            obj = json.loads(value) if isinstance(value, str) and value else {}
            return obj if isinstance(obj, dict) else {}
        except (ValueError, TypeError):
            return {}

    def top(book):
        try:
            if book is None or not book.buy_orders or (not book.sell_orders):
                return None
            if any((type(p) is not int or p < 0 or type(q) is not int or (q <= 0) for p, q in book.buy_orders.items())):
                return None
            if any((type(p) is not int or p <= 0 or type(q) is not int or (q >= 0) for p, q in book.sell_orders.items())):
                return None
            b, a = (max(book.buy_orders), min(book.sell_orders))
            if b >= a:
                return None
            return (b, a, (b + a) / 2, book.buy_orders[b], -book.sell_orders[a])
        except (AttributeError, TypeError, ValueError, OverflowError):
            return None

    def target_orders(symbol, book, position, target, clip=5):
        t = top(book)
        if t is None or type(position) is not int:
            return []
        target = max(-LIMITS[symbol], min(LIMITS[symbol], int(target)))
        diff = target - position
        if diff > 0:
            return [Order(symbol, t[1], min(diff, clip, t[4]))]
        if diff < 0 and t[0] > 0:
            return [Order(symbol, t[0], -min(-diff, clip, t[3]))]
        return []

    """A: bounded AMETHYST maker. Official example supplies fair value 10000.

No historical dataset, clock regimes, hidden instance state, or synthetic fills.
Research uses core helpers; the integration builder must inline them.
"""
    A_DEFAULT_CONFIG = {'fair_value': 10000, 'min_edge': 1, 'position_cap': 20, 'order_size': 5, 'quote_improvement': 0, 'inventory_step': 0}

    class AMETHYSTMaker:

        def __init__(self, config=None):
            self.config = dict(A_DEFAULT_CONFIG)
            if config is not None:
                self.config.update(config)
            for key, value in self.config.items():
                if type(value) is not int:
                    raise ValueError('A configuration values must be integers')
            c = self.config
            if c['fair_value'] <= 1 or c['min_edge'] < 1 or (not 1 <= c['position_cap'] <= LIMITS['AMETHYST']) or (c['order_size'] < 1) or (c['quote_improvement'] < 0) or (c['inventory_step'] < 0):
                raise ValueError('invalid A configuration')

        def run(self, state):
            p = 'AMETHYST'
            book = state.order_depths.get(p)
            t = top(book)
            position = state.position.get(p, 0)
            if t is None or type(position) is not int or abs(position) > LIMITS[p]:
                return ({}, 0, '{}')
            c = self.config
            cap = c['position_cap']
            buy_qty = max(0, min(c['order_size'], cap - position))
            sell_qty = max(0, min(c['order_size'], cap + position))
            retreat = abs(position) // c['inventory_step'] if c['inventory_step'] else 0
            bid_ceiling = c['fair_value'] - c['min_edge'] - (retreat if position > 0 else 0)
            ask_floor = c['fair_value'] + c['min_edge'] + (retreat if position < 0 else 0)
            bid = min(t[0] + c['quote_improvement'], bid_ceiling, t[1] - 1)
            ask = max(t[1] - c['quote_improvement'], ask_floor, t[0] + 1)
            orders = []
            if buy_qty and bid > 0:
                orders.append(Order(p, int(bid), int(buy_qty)))
            if sell_qty and ask > 0:
                orders.append(Order(p, int(ask), -int(sell_qty)))
            return ({p: orders}, 0, '{}')

    """F: causal neighboring-strike option relative value, with optional actual-fill delta hedge.

Black-Scholes-style r=q=0 total-variance formula is an explicit modeling assumption.
No option exercise, settlement, conversion, annualized volatility, or known fair price.
Only the target option and LYCHEE can receive orders; references supply current data.
"""
    F_TARGET = 'VOUCHER_7500'
    F_UNDERLYING = 'LYCHEE'
    F_LOW = 'VOUCHER_7400'
    F_HIGH = 'VOUCHER_7600'
    F_PRODUCTS = [F_UNDERLYING, F_LOW, F_TARGET, F_HIGH]
    F_DEFAULTS = {'edge': 3.0, 'hedge': False, 'hedge_band': 2.0, 'option_cap': 10, 'underlying_cap': 20, 'clip': 2, 'exit_edge': 1.0}

    def F_normal_cdf(x):
        return 0.5 * (1.0 + math.erf(x / math.sqrt(2.0)))

    def F_call_value_delta(spot, strike, total_variance):
        """Undiscounted call approximation; d/dspot holds total variance fixed."""
        if not all((isinstance(x, (int, float)) and math.isfinite(x) for x in (spot, strike, total_variance))) or spot <= 0 or strike <= 0 or (total_variance <= 0):
            return None
        vol_root = math.sqrt(total_variance)
        d1 = (math.log(spot / strike) + total_variance / 2.0) / vol_root
        d2 = d1 - vol_root
        delta = F_normal_cdf(d1)
        return (spot * delta - strike * F_normal_cdf(d2), delta)

    def F_implied_total_variance(spot, strike, price):
        if not all((isinstance(x, (int, float)) and math.isfinite(x) for x in (spot, strike, price))) or spot <= 0 or strike <= 0 or (price <= max(spot - strike, 0.0)) or (price >= spot):
            return None
        lo, hi = (1e-08, 1.0)
        if F_call_value_delta(spot, strike, lo)[0] > price or F_call_value_delta(spot, strike, hi)[0] < price:
            return None
        for _ in range(28):
            mid = (lo + hi) / 2.0
            if F_call_value_delta(spot, strike, mid)[0] < price:
                lo = mid
            else:
                hi = mid
        return (lo + hi) / 2.0

    def F_model_from_books(books):
        """The target option book is deliberately NEVER read by calibration."""
        underlying = top(books.get(F_UNDERLYING))
        lower, higher = (top(books.get(F_LOW)), top(books.get(F_HIGH)))
        if underlying is None or lower is None or higher is None:
            return None
        spot = underlying[2]
        low_w = F_implied_total_variance(spot, 7400, lower[2])
        high_w = F_implied_total_variance(spot, 7600, higher[2])
        if low_w is None or high_w is None:
            return None
        total_variance = (low_w + high_w) / 2.0
        fair, delta = F_call_value_delta(spot, 7500, total_variance)
        return (fair, delta, total_variance)

    class VoucherRelativeValue:

        def __init__(self, config=None):
            self.config = dict(F_DEFAULTS)
            if config:
                self.config.update(config)

        def run(self, state):
            c = self.config
            memory = read_memory(getattr(state, 'traderData', ''))
            count = memory.get('calls', 0)
            if type(count) is not int or count < 0 or count > 1000000:
                count = 0
            new_memory = {'version': 1, 'calls': count + 1}
            books = getattr(state, 'order_depths', {})
            positions = getattr(state, 'position', {})
            if not isinstance(books, dict) or not isinstance(positions, dict):
                return ({}, 0, json.dumps(new_memory))
            q = positions.get(F_TARGET, 0)
            hedge_q = positions.get(F_UNDERLYING, 0)
            if type(q) is not int or type(hedge_q) is not int or abs(q) > LIMITS[F_TARGET] or (abs(hedge_q) > LIMITS[F_UNDERLYING]):
                return ({}, 0, json.dumps(new_memory))
            model = F_model_from_books(books)
            target_top = top(books.get(F_TARGET))
            if model is None or target_top is None:
                return ({}, 0, json.dumps(new_memory))
            fair, delta, total_variance = model
            new_memory['last_total_variance'] = total_variance
            new_memory['last_model_delta'] = delta
            cap = min(LIMITS[F_TARGET] // 2, max(0, int(c['option_cap'])))
            target = q
            if target_top[1] < fair - c['edge']:
                target = cap
            elif target_top[0] > fair + c['edge']:
                target = -cap
            elif q > 0 and target_top[0] >= fair - c['exit_edge']:
                target = 0
            elif q < 0 and target_top[1] <= fair + c['exit_edge']:
                target = 0
            target = max(-cap, min(cap, target))
            orders = {}
            option_orders = target_orders(F_TARGET, books[F_TARGET], q, target, clip=c['clip'])
            if option_orders:
                orders[F_TARGET] = option_orders
            if c['hedge']:
                hedge_cap = min(LIMITS[F_UNDERLYING] // 2, max(0, int(c['underlying_cap'])))
                desired = max(-hedge_cap, min(hedge_cap, round(-q * delta)))
                if abs(desired - hedge_q) > c['hedge_band']:
                    hedge_orders = target_orders(F_UNDERLYING, books[F_UNDERLYING], hedge_q, desired, clip=c['clip'])
                    if hedge_orders:
                        orders[F_UNDERLYING] = hedge_orders
            return (orders, 0, json.dumps(new_memory, separators=(',', ':'), allow_nan=False))

    MODULE_SPECS = {'A': {'config': {'fair_value': 10000, 'min_edge': 1, 'position_cap': 20, 'order_size': 5, 'quote_improvement': 0, 'inventory_step': 0}, 'data_products': ['AMETHYST'], 'traded_products': ['AMETHYST']}, 'F': {'config': {'edge': 6.0, 'hedge': False, 'hedge_band': 2.0, 'option_cap': 10, 'underlying_cap': 20, 'clip': 2, 'exit_edge': 1.0}, 'data_products': ['LYCHEE', 'VOUCHER_7400', 'VOUCHER_7500', 'VOUCHER_7600'], 'traded_products': ['VOUCHER_7500']}}
    RISK_CAPS = {'AMETHYST':20, 'VOUCHER_7500':10}

    class Trader:
        """QuantiFi candidate. Cold-start safe; all temporal state is in traderData.

    A: AMETHYST passive fair-value quotes, soft cap 20, clip 5.
    F: VOUCHER_7500 relative pricing, soft cap 10, clip 2; UNHEDGED.
    Not officially backtested; see the project research report for assumptions.
    active_modules is used only for local removal experiments; official use is Trader().
    """
        def __init__(self, active_modules=None):
            self.active_modules = tuple(('A', 'F') if active_modules is None else active_modules)
            if len(set(self.active_modules)) != len(self.active_modules) or any(x not in ('A','F') for x in self.active_modules):
                raise ValueError('Unknown or duplicate module')

        def run(self, state):
            books = getattr(state, 'order_depths', None)
            positions = getattr(state, 'position', None)
            memory = read_memory(getattr(state, 'traderData', ''))
            saved = memory.get('modules', {})
            if not isinstance(saved, dict): saved = {}
            out_memory = {'version': 1, 'modules': {}, 'risk_diagnostics': []}
            if not isinstance(books, dict) or not isinstance(positions, dict):
                out_memory['risk_diagnostics'].append('invalid_state_mapping')
                return {}, 0, json.dumps(out_memory, separators=(',', ':'))
            orders = {}
            for name in self.active_modules:
                spec = MODULE_SPECS[name]
                text = saved.get(name, '{}')
                if not isinstance(text, str): text = '{}'
                view = SimpleNamespace(
                    traderData=text, timestamp=getattr(state, 'timestamp', 0),
                    order_depths={p:books[p] for p in spec['data_products'] if p in books},
                    position={p:positions[p] for p in spec['data_products'] if p in positions},
                    listings=getattr(state, 'listings', {}),
                    own_trades=getattr(state, 'own_trades', {}),
                    market_trades=getattr(state, 'market_trades', {}),
                    observations=getattr(state, 'observations', None))
                try:
                    strategy = AMETHYSTMaker(spec['config']) if name == 'A' else VoucherRelativeValue(spec['config'])
                    returned = strategy.run(view)
                    if not isinstance(returned, tuple) or len(returned) != 3:
                        out_memory['risk_diagnostics'].append(name + ':invalid_module_return')
                        continue
                    proposed, conversions, next_text = returned
                    if isinstance(next_text, str) and next_text:
                        json.loads(next_text)
                except Exception as exc:
                    out_memory['risk_diagnostics'].append(name + ':module_exception:' + type(exc).__name__)
                    continue
                if type(conversions) is not int or conversions != 0 or not isinstance(proposed, dict) or not isinstance(next_text, str):
                    out_memory['risk_diagnostics'].append(name + ':invalid_module_return')
                    continue
                out_memory['modules'][name] = next_text
                for p, rows in proposed.items():
                    if p not in spec['traded_products'] or not isinstance(rows, list):
                        out_memory['risk_diagnostics'].append(name + ':ownership_violation')
                        continue
                    orders.setdefault(p, []).extend(rows)
            safe = {}
            for p, rows in orders.items():
                position = positions.get(p, 0)
                cap = RISK_CAPS[p]
                if type(position) is not int or abs(position) > LIMITS[p] or top(books.get(p)) is None:
                    out_memory['risk_diagnostics'].append(p + ':invalid_position_or_book')
                    continue
                buys = max(0, cap-position)
                sells = max(0, cap+position)
                clean = []
                for order in rows:
                    if (not isinstance(order, Order) or order.symbol != p or type(order.price) is not int
                        or order.price <= 0 or type(order.quantity) is not int or order.quantity == 0):
                        out_memory['risk_diagnostics'].append(p + ':invalid_order')
                        continue
                    amount = min(abs(order.quantity), buys if order.quantity > 0 else sells)
                    if amount < abs(order.quantity):
                        out_memory['risk_diagnostics'].append(p + ':risk_clip')
                    if amount:
                        clean.append(Order(p, order.price, amount if order.quantity > 0 else -amount))
                        if order.quantity > 0: buys -= amount
                        else: sells -= amount
                bp = [o.price for o in clean if o.quantity > 0]
                ap = [o.price for o in clean if o.quantity < 0]
                if bp and ap and max(bp) >= min(ap):
                    out_memory['risk_diagnostics'].append(p + ':self_cross_rejected')
                    continue
                if clean: safe[p] = clean
            return safe, 0, json.dumps(out_memory, separators=(',', ':'), allow_nan=False)
    return _Namespace(locals())
