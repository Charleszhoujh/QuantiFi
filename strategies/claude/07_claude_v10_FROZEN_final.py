# Module MANGOSTEEN__MR500_z2 - MANGOSTEEN slow mean reversion
# ======================================================================================
def _build_plugin_broad_single(env):
    Order = env['Order']
    LIMITS = env['LIMITS']
    top = env['top']
    read_memory = env['read_memory']
    original = env['original']
    PEARLS = env['PEARLS']
    pending = env['pending']
    target_order = env['target_order']
    detector = env['detector']
    structure = env['structure']
    wave = env['wave']
    claude_I = env['claude_I']
    """Registered single-product MR and passive fair-value proposals.

No data access, fills, end liquidation or parameter search is performed here.
The shared portfolio gate owns official worst-case exposure and order lifetime.
All temporal state is returned as JSON-compatible module memory.
"""
    import copy
    import math


    def alpha(half_life):
        return 1.0 - 0.5 ** (1.0 / half_life)


    def empty_block(timestamp):
        return dict(count=0, sum_x=0.0, sum_y=0.0, sum_xx=0.0,
                    sum_xy=0.0, complete=True, first_timestamp=timestamp,
                    last_label_timestamp=None)


    def fit_ar1(block, train_first_clock, train_last_clock):
        """OLS with intercept, only a complete prior 2000-observation block."""
        count=block.get('count',0)
        result=dict(valid=False, intercept=0.0, beta=0.0, samples=count,
                    train_first_clock=train_first_clock,
                    train_last_clock=train_last_clock,
                    train_first_timestamp=block.get('first_timestamp'),
                    train_last_label_timestamp=block.get('last_label_timestamp'))
        if not block.get('complete',False) or count != 1998:
            return result
        sx=block['sum_x']; sy=block['sum_y']
        xx=block['sum_xx']-sx*sx/count
        if xx <= 1e-12:
            return result
        beta=(block['sum_xy']-sx*sy/count)/xx
        intercept=(sy-beta*sx)/count
        if math.isfinite(beta) and math.isfinite(intercept):
            result.update(valid=True,intercept=intercept,beta=beta)
        return result


    def advance_ar1(memory, clock, timestamp, mid):
        """Freeze previous block before processing the current observed change.

    At offset 0 the new block starts; its first within-block return is at
    offset 1, so paired returns first enter the fit at offset 2. Missing
    quotes invalidate a whole block and never create a stitched gap return.
    The current feature can cross a block boundary, but its label cannot be
    part of the already frozen model.
    """
        m=memory
        block=m.get('ar_block')
        model=m.get('ar_model',dict(valid=False,intercept=0.0,beta=0.0,samples=0,
                                   train_first_clock=None,train_last_clock=None,
                                   train_first_timestamp=None,
                                   train_last_label_timestamp=None))
        offset=clock % 2000
        if offset == 0:
            if clock:
                model=fit_ar1(block or {},clock-2000,clock-1)
            block=empty_block(timestamp)
        elif block is None:
            block=empty_block(timestamp)
            block['complete']=False
        contiguous=(mid is not None and m.get('last_quote_clock')==clock-1
                    and m.get('last_mid') is not None)
        change=mid-m['last_mid'] if contiguous else None
        prior_within=m.get('within_delta') if offset >= 2 else None
        if mid is None:
            block['complete']=False
        if offset >= 1:
            if change is None:
                block['complete']=False
            if offset >= 2:
                if change is None or prior_within is None:
                    block['complete']=False
                else:
                    x=prior_within; y=change
                    block['count']+=1
                    block['sum_x']+=x; block['sum_y']+=y
                    block['sum_xx']+=x*x; block['sum_xy']+=x*y
                    block['last_label_timestamp']=timestamp
        m.update(ar_model=model,ar_block=block,
                 within_delta=change if offset >= 1 else None)
        if mid is not None:
            m.update(last_mid=mid,last_quote_clock=clock)
        return change,model


    def mean_reversion(state, memory, c, quote, clock):
        p=c['product']; cap=c['cap']; q=state.position.get(p,0)
        held=pending(state,p); n=memory.get('observed',0)
        side=memory.get('side',0); exiting=bool(memory.get('exiting',False))
        entered=memory.get('entry_clock'); just_flat=False; reason=None
        if exiting and q==0 and not any(held):
            exiting=False; just_flat=True; side=0; entered=None
        if side and entered is not None and clock-entered>=1000:
            exiting=True; reason='holding_horizon'
        fair=memory.get('ema')
        variance=memory.get('residual_variance',0.0)
        scale=math.sqrt(max(1.0,variance))
        score=None; entry_side=0
        if quote is not None:
            bid,ask,mid,_,_=quote
            if fair is None:fair=mid
            score=(fair-mid)/scale
            if side and (side*(mid-fair)>=0):
                exiting=True; reason=reason or 'mid_crossed_prior_mean'
            if side and (q*side<0 or (held[1] if side>0 else held[0])):
                # A stale opposing order or unexpected sign must resolve at zero.
                exiting=True; reason=reason or 'opposing_exposure_cleanup'
            if not side and not exiting and not just_flat:
                if q or any(held):
                    exiting=True; reason='orphan_exposure_cleanup'
                elif n>=500:
                    if ask < fair-c['z']*scale:entry_side=1
                    elif bid > fair+c['z']*scale:entry_side=-1
                    if entry_side:
                        side=entry_side; entered=clock
            residual=mid-fair
            memory.update(ema=fair+alpha(c['half_life'])*(mid-fair),
                          residual_variance=variance+alpha(500)*(residual*residual-variance),
                          observed=n+1)
        target=0 if exiting or just_flat else side*cap
        rows=[]
        if quote is not None and target!=q and not just_flat:
            rows=target_order(state,p,target,quote[1] if target>q else quote[0],
                              quote[4] if target>q else quote[3])
        memory.update(side=side,entry_clock=entered,exiting=exiting,
                      diagnostic=dict(timestamp=state.timestamp,clock=clock,method='mr',
                        quote_present=quote is not None,prior_n=n,ready=n>=500,
                        mid=quote[2] if quote else None,prior_fair=fair,
                        prior_residual_variance=variance,prior_scale=scale,score=score,
                        entry_side=entry_side,side=side,entry_clock=entered,
                        age=clock-entered if entered is not None else None,
                        target=target,position=q,pending=list(held),exiting=exiting,
                        just_flat=just_flat,exit_reason=reason,
                        orders=[[o.price,o.quantity] for o in rows]))
        return ({p:rows} if rows else {}),memory


    def market_make(state, memory, c, quote, clock):
        p=c['product']; cap=c['cap']; q=state.position.get(p,0); held=pending(state,p)
        n=memory.get('observed',0); mid=quote[2] if quote else None
        change,model=advance_ar1(memory,clock,state.timestamp,mid)
        forecast=0.0
        if c['fair_model']=='ar1' and model['valid'] and change is not None:
            forecast=model['intercept']+model['beta']*change
        fair=mid+forecast if mid is not None else None
        reservation=fair-c['skew']*q/cap if fair is not None else None
        buy_room=max(0,cap-q-held[0]); sell_room=max(0,cap+q-held[1])
        rows=[]; bid_price=ask_price=None
        if quote is not None and n>=2000:
            bid_price=min(math.floor(reservation-c['width']),quote[1]-1)
            ask_price=max(math.ceil(reservation+c['width']),quote[0]+1)
            if bid_price>0 and buy_room:rows.append(Order(p,int(bid_price),buy_room))
            if ask_price>0 and sell_room:rows.append(Order(p,int(ask_price),-sell_room))
            # Positive width plus outward-only quote clipping must never self-cross.
            assert bid_price < ask_price
        if quote is not None:memory['observed']=n+1
        memory['diagnostic']=dict(timestamp=state.timestamp,clock=clock,method='maker',
            quote_present=quote is not None,prior_n=n,ready=n>=2000,mid=mid,
            current_observed_change=change,fair_model=c['fair_model'],forecast=forecast,
            fair=fair,reservation=reservation,width=c['width'],skew=c['skew'],
            position=q,pending=list(held),buy_room=buy_room,sell_room=sell_room,
            bid_price=bid_price,ask_price=ask_price,ar_model=dict(model),
            ar_training_count_after=memory['ar_block']['count'],
            ar_training_complete_after=memory['ar_block']['complete'],
            orders=[[o.price,o.quantity] for o in rows])
        return ({p:rows} if rows else {}),memory


    def propose(state, memory, c):
        p=c['product']; cap=c['cap']
        if type(cap) is not int or not 0<cap<=LIMITS[p]:raise ValueError('invalid research cap')
        m=copy.deepcopy(memory)
        if m.get('timestamp')==state.timestamp:return {},m
        clock=m.get('clock',0)
        q=state.position.get(p,0)
        if type(q) is not int or abs(q)>LIMITS[p]:return {},m
        quote=top(state.order_depths.get(p))
        if c['method']=='mr':result,m=mean_reversion(state,m,c,quote,clock)
        elif c['method']=='maker':result,m=market_make(state,m,c,quote,clock)
        else:raise ValueError('unknown registered single-product method')
        m.update(timestamp=state.timestamp,clock=clock+1)
        return result,m
    return _Namespace(locals())


