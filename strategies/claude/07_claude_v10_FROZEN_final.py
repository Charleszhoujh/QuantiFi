# Module passive_implied_w2 - PINK_PEARLS passive quotes around an implied fair value
# ======================================================================================
def _build_plugin_passive(env):
    Order = env['Order']
    LIMITS = env['LIMITS']
    top = env['top']
    read_memory = env['read_memory']
    original = env['original']
    PEARLS = env['PEARLS']
    pending = env['pending']
    target_order = env['target_order']
    detector = env['detector']
    structure = env['structure']
    wave = env['wave']
    claude_I = env['claude_I']
    """Causal PINK passive quotes; no redemption or guaranteed fill assumption.

The parent portfolio gate repeats official worst-side/pending limits. This
module also bounds quotes independently, and drains a prior quote generation
before entering explicit target-zero liquidation mode.
"""
    import math


    PINK = 'PINK_PEARLS'


    def _memory(value, position):
        """Only self-produced JSON-compatible state is reused; otherwise unwind."""
        if not isinstance(value, dict):
            value = {}
        ema = value.get('ema')
        good_ema = type(ema) in (float, int) and math.isfinite(ema) and ema > 0
        oldq = value.get('last_position', 0)
        age = value.get('age', 0)
        exiting = value.get('exiting', False)
        good = (good_ema and type(oldq) is int and abs(oldq) <= LIMITS[PINK]
                and type(age) is int and 0 <= age <= 1000000
                and type(exiting) is bool)
        if good:
            return {'ema': float(ema), 'last_position': oldq,
                    'age': age, 'exiting': exiting}, False
        return {'ema': None, 'last_position': position, 'age': 0,
                'exiting': bool(position)}, bool(position)


    def propose(state, memory, config):
        """Return current passive quotes or a persistent target-zero unwind.

    mode own_quote: EMA50(PINK mid) plus current microprice-minus-mid.
    mode implied: 50000 minus four other current mids.
    mode quarter: current PINK mid plus one quarter of implied-minus-mid.
    Every mode uses the same inventory skew and independent side capacity.
    Quotes are clipped so they cannot take the current opposing best price;
    an old quote can become marketable under the delayed scenario.
    """
        cap = config['position_cap']
        width, skew, max_hold = config['width'], config['skew'], config['max_hold']
        mode = config['mode']
        if type(cap) is not int or not 0 < cap <= LIMITS[PINK]:
            raise ValueError('invalid position_cap')
        if (mode not in ('own_quote', 'implied', 'quarter')
                or type(width) not in (int, float) or not math.isfinite(width) or width <= 0
                or type(skew) not in (int, float) or not math.isfinite(skew) or skew < 0
                or type(max_hold) is not int or max_hold < 0):
            raise ValueError('invalid passive config')
        q = state.position.get(PINK, 0)
        if type(q) is not int or abs(q) > LIMITS[PINK]:
            raise ValueError('invalid actual position')
        obj, must_drain = _memory(memory, q)
        quote = top(state.order_depths.get(PINK))
        if quote is None:
            return {}, obj
        bid, ask, mid, bqty, aqty = quote
        obj['ema'] = mid if obj['ema'] is None else obj['ema'] + (mid - obj['ema']) * (2.0 / 51.0)
        oldq = obj['last_position']
        obj['age'] = 0 if not q else (obj['age'] + 1 if q * oldq > 0 else 1)
        obj['last_position'] = q
        held = pending(state, PINK)
        if max_hold and q and obj['age'] >= max_hold and not obj['exiting']:
            obj['exiting'] = True
            must_drain = True
        if must_drain:
            # Old normal quotes can point through flat. Let their one supported
            # generation activate/expire before issuing any target-zero order.
            obj['reason'] = 'drain_before_exit'
            return {}, obj
        if obj['exiting']:
            if q == 0:
                if held == (0, 0):
                    obj['exiting'] = False
                    obj['age'] = 0
                obj['reason'] = 'flat_exit_pause'
                return {}, obj
            levels = state.order_depths[PINK].buy_orders if q > 0 else state.order_depths[PINK].sell_orders
            # Real shared simulator consumes actual available depth. No assumed
            # whole-position fill; retry next observation after pending reservation.
            limit = min(levels) if q > 0 else max(levels)
            rows = target_order(state, PINK, 0, limit)
            obj['reason'] = 'target_zero_exit'
            return ({PINK: rows} if rows else {}), obj
        micro = (ask * bqty + bid * aqty) / (bqty + aqty)
        if mode == 'own_quote':
            fair = obj['ema'] + micro - mid
            residual = None
        else:
            quotes = {p: top(state.order_depths.get(p)) for p in PEARLS}
            if any(v is None for v in quotes.values()):
                obj['reason'] = 'missing_other_quote'
                return {}, obj
            implied = 50000.0 - sum(v[2] for p, v in quotes.items() if p != PINK)
            residual = mid - implied
            fair = implied if mode == 'implied' else mid + 0.25 * (implied - mid)
        center = fair - skew * q / cap
        buy_price = min(math.floor(center - width), ask - 1)
        sell_price = max(math.ceil(center + width), bid + 1)
        buy_qty = max(0, cap - q - held[0])
        sell_qty = max(0, cap + q - held[1])
        rows = []
        if buy_qty and buy_price > 0:
            rows.append(Order(PINK, int(buy_price), buy_qty))
        if sell_qty and sell_price > 0:
            rows.append(Order(PINK, int(sell_price), -sell_qty))
        if rows and buy_price >= sell_price:
            raise AssertionError('self-crossing quotes')
        obj.update(reason='quote', fair=fair, residual=residual)
        return ({PINK: rows} if rows else {}), obj
    return _Namespace(locals())


