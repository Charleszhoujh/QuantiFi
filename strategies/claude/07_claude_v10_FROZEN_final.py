"""QuantiFi 2026 trading algorithm - readable edition of the portal-verified v9.

Portal backtest (days -2, -1, 0): 225,130 / 188,395 / 109,666.5  ->  523,191.5 Coins.
This file is a mechanical, behaviour-preserving restructuring of v9: every order and
fill on all three days was verified identical to the portal-verified version.

HOW TO READ THIS FILE
---------------------
The algorithm is a portfolio of independent per-product modules. Each module owns its
products (no two modules trade the same product), keeps its own memory, and returns
orders; a root risk gate checks position limits and in-flight orders. Sections below,
top to bottom:

  1. Shared helpers and models ............ _build_original, _build_helpers,
                                             _build_detector, _build_structure, ...
  2. Strategy modules (one builder each) ... _build_plugin_<name>
  3. Portfolio root / risk gate ............ _build_portfolio, FROZEN_CONFIG, _CodexTrader
  4. TOFFEE / JELLY blend ................... _build_tj, TJ_CONFIG
  5. GOLDEN_PEARLS maker .................... _build_gp, GP_CONFIG
  6. traderData compaction ................. _td_pack / _td_unpack
  7. Root Trader + intraday kill switch .... Trader, _kill_switch

PRODUCTS AND STRATEGIES (18 traded, 7 distinct strategy families)
-----------------------------------------------------------------
  AMETHYST          market making around the official fair value 10,000
  VOUCHER_7000..7900  options relative value: each strike's fair value is fitted from
                    the OTHER strikes' implied variances (quadratic smile); trade when the
                    quote deviates by more than 7
  PAPER_LANTERNS    trend timing on a 50-tick OLS slope with a fair-value gate
  TELLURIUM         breakout of confirmed swing pivots (causal pivot detector), cap 40
  FRUIT_BASKET      own-price trend (EMA cross), cap 40
  PEANUT_BUTTER     mean reversion: z = (mid - EMA500) / EWMA std, enter at |z| >= 2,
                    exit at the anchor frozen at entry, 1000-tick time stop
  TOFFEE_CAKE, JELLY  mean reversion split across two models of the centre: 25 lots on a
                    fixed centre (5000 / 2000) and 25 lots on an adaptive EMA(3000) centre
                    with a volatility-scaled entry; orders take only the best level
  MANGOSTEEN        slow mean reversion (EMA500, z 2)
  PINK_PEARLS       passive quotes around an implied fair value
  GOLDEN_PEARLS     Avellaneda-Stoikov style passive maker, inventory skew, +-10 lots

  Not traded (researched and rejected): WHITE/BLACK/BLUE_PEARLS, DRAGONFRUIT,
  GRANADILLA, LYCHEE, VOUCHER_6800, VOUCHER_8100.

RISK CONTROLS
-------------
  * Position limits and in-flight (pending) orders are reserved before any order is sent.
  * Intraday kill switch on the three trend modules (TELLURIUM, FRUIT_BASKET,
    PAPER_LANTERNS): if a product's own PnL falls more than 1.5x its largest historical
    intraday drawdown below its intraday peak, it is flattened and stops for the day.
    The flatten never crosses zero, counts every possibly-working order, and books each
    own fill exactly once.
  * Duplicate-callback guard (same timestamp twice -> no orders).

PLATFORM FACTS MEASURED ON THE PORTAL (with small probe strategies)
-------------------------------------------------------------------------------
  * unfilled orders live one tick;
  * traderData is capped at about 8.5 KB (beyond it the state is lost), so memory is
    packed losslessly (peak about 5 KB);
  * own_trades re-sends the latest fill batch until a newer one arrives, so fills are
    de-duplicated by timestamp.
Only `datamodel` and the Python standard library are used.
"""

