# Wave-signal execution helpers (same source as plugin causal_wave)
# ======================================================================================
def _build_wave_transfer(env):
    Order = env['Order']
    LIMITS = env['LIMITS']
    top = env['top']
    read_memory = env['read_memory']
    original = env['original']
    PEARLS = env['PEARLS']
    pending = env['pending']
    target_order = env['target_order']
    detector = env['detector']
    structure = env['structure']
    """Causal wave entries, confirmed-pivot stops, full-cap execution with pending."""
    from copy import deepcopy

    def fresh():return {'v':1,'n':-1,'last_ts':None,'detector':{},'ema':{},'event':None,'consumed':None,'diagnostic':{}}

    def propose(state,memory,c):
        m=deepcopy(memory) if memory else fresh();p=c['product'];book=state.order_depths.get(p);t=top(book)
        if t is None:return {},m
        q=state.position.get(p,0);ts=state.timestamp
        if (not isinstance(m,dict) or m.get('v')!=1 or type(m.get('n'))is not int or
            not isinstance(m.get('ema'),dict) or not isinstance(m.get('detector'),dict)):
            m=fresh();m['last_ts']=ts;m['diagnostic']={'reason':'malformed_one_generation_pause'};return {},m
        if m['last_ts'] is not None and ts<=m['last_ts']:
            m['diagnostic']={'reason':'nonadvancing_callback_no_new_order'};return {},m
        m['n']+=1;n=m['n'];m['last_ts']=ts;mid=t[2];cap=c['cap'];pv=None;setup=None;side=0
        d={'index':n,'timestamp':ts,'mid':mid,'pivot':None,'setup':None,'signal':0,'action':'none','reason':''};m['diagnostic']=d
        if c['signal']=='wave':
            try:m['detector'],pv=detector.step(mid,n,ts,m['detector'],c['threshold'])
            except ValueError:
                # Explicit pause, no invented pivot history; held inventory recovers below.
                m['detector']={};d['reason']='invalid_detector_pause';return {},m
            d['pivot']=pv
            setup=structure.setup(m['detector']['pivots'],c['mode'],c['fib'],asof_index=n)
            d['setup']=setup
            if setup is not None and setup['side']*(mid-setup['breakout'])>0:side=setup['side']
        else:
            em=m['ema'];count=em.get('n',0);fast=em.get('fast',mid);slow=em.get('slow',mid)
            if count:
                fast+=2/(c['fast']+1)*(mid-fast);slow+=2/(c['slow']+1)*(mid-slow)
            direction=1 if fast>slow else -1 if fast<slow else em.get('side',0)
            m['ema']={'n':count+1,'fast':round(fast,6) if c.get('round6') else fast,'slow':round(slow,6) if c.get('round6') else slow,'side':direction}
            if count+1>=c['warmup']:side=direction
        d['signal']=side
        e=m['event'];held=pending(state,p)
        if e is None and q:
            e={'side':1 if q>0 else -1,'phase':'exit','stop':None,'seen_fill':True,'id':'recover','start_index':n};m['event']=e;d['reason']='orphan_position_exit'
        def send(target,action,reason):
            diff=target-q
            if not diff:return {}
            qty=t[4] if diff>0 else t[3];price=t[1] if diff>0 else t[0]
            orders=target_order(state,p,target,price,clip=qty)
            if orders:d.update(action=action,reason=reason,target=target)
            return {p:orders} if orders else {}
        if e is not None:
            if q:e['seen_fill']=True
            if q and q*e['side']<0:e['phase']='exit';d['reason']='unexpected_side_exit'
            if c['signal']=='wave' and pv is not None and e['phase']!='exit':
                if pv['kind']==('L' if e['side']>0 else 'H'):
                    if e['stop'] is None or e['side']*(pv['price']-e['stop'])>0:e['stop']=pv['price']
            stop_hit=e['stop'] is not None and e['side']*(mid-e['stop'])<=0
            if e['phase']!='exit' and (stop_hit or side*e['side']<0):
                e['phase']='exit';d['reason']='confirmed_stop' if stop_hit else 'opposite_signal'
            if e['phase']=='exit':
                if q:return send(0,'exit',d['reason'] or 'latched_exit'),m
                if any(held):d['reason']='wait_pending_exit';return {},m
                m['event']=None;d['action']='exit_complete';return {},m
            return send(e['side']*cap,'stage','retain_original_target'),m
        if any(held):d['reason']='wait_prior_generation';return {},m
        if not side:return {},m
        ident=setup['setup_id'] if setup is not None else 'ema:'+str(side)
        if c['signal']=='wave' and ident==m['consumed']:d['reason']='setup_already_consumed';return {},m
        m['consumed']=ident;m['event']={'side':side,'phase':'holding','stop':setup['stop'] if setup else None,'seen_fill':False,'id':ident,'start_index':n}
        return send(side*cap,'entry','confirmed_breakout' if setup else 'ema_direction'),m
    return _Namespace(locals())
