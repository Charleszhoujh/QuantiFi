# Band / tranche mean-reversion estimator used by the PEANUT_BUTTER module
# ======================================================================================
def _build_claude_I(env):
    """Direction I: mean-reversion legs with graded (tranche) position functions and
optional risk overlays. Non-option products only (never vouchers or LYCHEE).

Provenance
  - 'D' z and the band state machine (entry / exit / max_hold time stop / side
    block) are copied from research/D/strategy.py (_band) and generalised from one
    position block to K tranches. With one tranche [[entry, exit]] and the same
    parameters the orders are identical to research/D's band leg.
  - 'E' z is re-implemented from research/E/strategy.py (single-leg 'jelly' pair:
    level s accumulated from mid changes, EWMA mean/variance with half-life hl,
    z formed from PRIOR statistics, warm-up counted in updates).

Per leg (config['legs'][symbol]):
  zmode      'D': dev = mid - EMA(mid) (prior anchor, half-life anchor_hl),
                  var = EWMA(dev^2) (half-life sd_hl), z = dev / sqrt(var) once n >= warmup.
             'E': s = level built from mid changes, mu/var EWMA of s (anchor_hl / sd_hl),
                  z = (s - mu_prev)/sqrt(var_prev) once n > warmup.
  tranches   list of [e_k, x_k]: tranche k is long (+1) while z <= -e_k until z >= -x_k,
             short (-1) while z >= e_k until z <= x_k (hysteresis width e_k - x_k).
             Target position = sum_k state_k * size_k, size_k = near-equal integer split
             of `size`. One tranche = the binary band of research/D / research/E.
  max_hold   time stop per tranche (ticks in the same state); flattens that tranche and
             blocks its side until z is back at the tranche's exit level (as in D).
  z_stop     (H3) loss stop: a tranche whose |z| moved to >= z_stop against it is closed
             and its side blocked until z is back at its exit level.
  debias     (H3) divide the EWMA variance by its start-up weight 1-(1-alpha)^m
             (m = variance updates so far); removes the start-of-day under-estimate.
  volscale   (H3) tranche size fixed AT ENTRY as size_k * min(1, mean_sigma / sigma_t),
             mean_sigma = running mean of the leg's sigma over ticks with z defined.
  flip       control only: same state machine, opposite sign (momentum).
Execution: take-only at level 1, quantity capped by visible level-1 volume and the
limit (no residual rests, so fills do not depend on the passive-fill model).
While z is unavailable (warm-up / reset) the leg flattens any position it holds.

Only datamodel + standard library. All cross-tick state lives in traderData.
Each leg reads ONLY its own symbol's order book and position.
"""
    import json
    import math

    from datamodel import Order, OrderDepth, TradingState  # noqa: F401

    # Official Wiki position limits (core/common.py, read 2026-10-27).
    LIMITS = {'TOFFEE_CAKE': 50, 'JELLY': 50, 'PEANUT_BUTTER': 50, 'TELLURIUM': 40,
              'DRAGONFRUIT': 40, 'GRANADILLA': 40, 'MANGOSTEEN': 40, 'FRUIT_BASKET': 40,
              'WHITE_PEARLS': 20, 'BLACK_PEARLS': 20, 'GOLDEN_PEARLS': 20, 'PINK_PEARLS': 20,
              'BLUE_PEARLS': 20}
    FORBIDDEN = ('LYCHEE', 'VOUCHER_')   # never traded by this module (BRIEF.txt)

    LEG_DEFAULTS = {'zmode': 'D', 'anchor_hl': 500.0, 'sd_hl': 1000.0, 'warmup': 300, 'size': 50,
                    'tranches': [[1.5, 0.0]], 'max_hold': None, 'z_stop': None,
                    'debias': False, 'volscale': False, 'flip': False}

    # Incumbent replicas (research/D nominee TOFFEE leg; research/E R2_J_own JELLY 50).
    TOFFEE_BIN = {'zmode': 'D', 'anchor_hl': 500, 'sd_hl': 1000, 'warmup': 300, 'size': 50,
                  'tranches': [[1.5, 0.0]], 'max_hold': 1000}
    JELLY_BIN = {'zmode': 'E', 'anchor_hl': 1000, 'sd_hl': 1000, 'warmup': 1000, 'size': 50,
                 'tranches': [[2.0, 0.5]], 'max_hold': None}

    # Nominee configuration, set AFTER the registered selection (results/selection.json):
    # H2_VRscreen_posthoc = research/D band rule, size = limit, on the products passing the
    # post-hoc VR screen (status conditional; see candidate.json). Registered runs always pass
    # explicit 'legs', so this default does not affect any logged result. TOFFEE/JELLY: the
    # selection kept the incumbents (TOFFEE_BIN / JELLY_BIN replicas above).
    _H2_BAND = {'zmode': 'D', 'anchor_hl': 500, 'sd_hl': 1000, 'warmup': 300,
                'tranches': [[1.5, 0.0]], 'max_hold': 1000}
    DEFAULTS = {'legs': {'PEANUT_BUTTER': {**_H2_BAND, 'size': 50},
                         'BLACK_PEARLS': {**_H2_BAND, 'size': 20},
                         'BLUE_PEARLS': {**_H2_BAND, 'size': 20}}}
    PRODUCTS = tuple(sorted(DEFAULTS['legs']))   # products the DEFAULT config reads/trades


    def _num(x):
        """Finite float or None (rejects bool/str/NaN/inf from corrupted memory)."""
        if isinstance(x, bool) or not isinstance(x, (int, float)):
            return None
        x = float(x)
        return x if math.isfinite(x) else None


    def _int(x, lo, hi, default):
        return x if (type(x) is int and lo <= x <= hi) else default


    def _load(raw):
        try:
            obj = json.loads(raw) if isinstance(raw, str) and raw else {}
        except (ValueError, TypeError):
            return {}
        return obj if isinstance(obj, dict) else {}


    def _top(book):
        """(bb, ba, bid_vol, ask_vol) or None for a missing / one-sided / crossed book."""
        try:
            if book is None or not book.buy_orders or not book.sell_orders:
                return None
            bb, ba = max(book.buy_orders), min(book.sell_orders)
            bv, av = book.buy_orders[bb], -book.sell_orders[ba]
            if type(bb) is not int or type(ba) is not int or bb >= ba or bb <= 0:
                return None
            if type(bv) is not int or type(av) is not int or bv <= 0 or av <= 0:
                return None
            return bb, ba, bv, av
        except (AttributeError, TypeError, ValueError):
            return None


    def _alpha(hl):
        return 1.0 - 0.5 ** (1.0 / float(hl))


    def _split(size, k):
        base, rem = divmod(size, k)
        return [base + (1 if i < rem else 0) for i in range(k)]


    class Trader:
        def __init__(self, config=None):
            cfg = dict(DEFAULTS)
            cfg.update(config or {})
            legs = {}
            for sym, leg in (cfg.get('legs') or {}).items():
                if sym not in LIMITS or any(sym.startswith(f) for f in FORBIDDEN):
                    continue
                leg = {**LEG_DEFAULTS, **leg}
                leg['tranches'] = [[float(e), float(x)] for e, x in leg['tranches']]
                leg['size'] = max(0, min(int(leg['size']), LIMITS[sym]))
                leg['sizes'] = _split(leg['size'], len(leg['tranches']))
                legs[sym] = leg
            self.legs = legs

        # ------------------------------------------------------------------ run
        def run(self, state):
            mem = _load(getattr(state, 'traderData', ''))
            depths = getattr(state, 'order_depths', None) or {}
            positions = getattr(state, 'position', None) or {}
            out_mem, orders = {}, {}
            for sym, leg in self.legs.items():
                m = mem.get(sym)
                m = m if isinstance(m, dict) else {}
                tob = _top(depths.get(sym))
                if tob is None:              # no usable book: keep memory, no orders
                    if m:
                        out_mem[sym] = m
                    continue
                pos = positions.get(sym, 0)
                pos = pos if type(pos) is int and abs(pos) <= LIMITS[sym] else 0
                o, m = self._leg(sym, leg, tob, pos, m)
                out_mem[sym] = m
                if o:
                    orders[sym] = o
            return orders, 0, json.dumps(out_mem, separators=(',', ':'))

        # ------------------------------------------------------------- signal
        def _z(self, leg, mid, m):
            """Advance the leg's estimator by one tick. Returns (z or None, sigma or None, new_m, fresh)."""
            if leg['zmode'] == 'E':
                pm, s, mu, v = _num(m.get('pm')), _num(m.get('s')), _num(m.get('mu')), _num(m.get('v'))
                n = _int(m.get('n'), 0, 10 ** 9, None)
                if None in (pm, s, mu, v, n) or v < 0:
                    return None, None, {'pm': mid, 's': 0.0, 'mu': 0.0, 'v': 0.0, 'n': 0}, True
                s += mid - pm
                n = min(n + 1, 10 ** 9)
                z = sig = None
                if n > int(leg['warmup']) and v > 0:
                    vv = v
                    if leg['debias']:
                        c = 1.0 - (1.0 - _alpha(leg['sd_hl'])) ** max(n - 1, 1)
                        vv = v / c if c > 0 else v
                    sig = math.sqrt(vv)
                    z = (s - mu) / sig
                e = s - mu
                mu += _alpha(leg['anchor_hl']) * e
                a = _alpha(leg['sd_hl'])
                v = (1.0 - a) * (v + a * e * e)
                # unrounded, as in research/E (exact replication of its z path)
                return z, sig, {'pm': mid, 's': s, 'mu': mu, 'v': v, 'n': n}, False
            a, v = _num(m.get('a')), _num(m.get('v'))
            n = _int(m.get('n'), 0, 10 ** 9, 0)
            fresh = False
            if a is None or (v is not None and v < 0):
                a, v, n, fresh = mid, None, 0, True
            dev = mid - a                           # deviation from the PRIOR anchor
            z = sig = None
            if v is not None and v > 0 and n >= int(leg['warmup']):
                vv = v
                if leg['debias']:
                    c = 1.0 - (1.0 - _alpha(leg['sd_hl'])) ** max(n - 1, 1)
                    vv = v / c if c > 0 else v
                sig = math.sqrt(vv)
                z = dev / sig
            v = dev * dev if v is None else v + _alpha(leg['sd_hl']) * (dev * dev - v)
            a = a + _alpha(leg['anchor_hl']) * (mid - a)
            n = min(n + 1, 10 ** 9)
            return z, sig, {'a': round(a, 4), 'v': round(v, 4), 'n': n}, fresh

        # ---------------------------------------------------------------- leg
        def _leg(self, sym, leg, tob, pos, m):
            bb, ba, bv, av = tob
            lim = LIMITS[sym]
            mid = (bb + ba) / 2.0
            k = len(leg['tranches'])
            z, sig, new_m, fresh = self._z(leg, mid, m)
            st = m.get('st')
            ok = (not fresh and isinstance(st, list) and len(st) == k
                  and all(type(x) is int and x in (-1, 0, 1) for x in st))
            st = list(st) if ok else [0] * k
            h = m.get('h') if ok else None
            h = list(h) if isinstance(h, list) and len(h) == k and all(type(x) is int and x >= 0 for x in h) else [0] * k
            b = m.get('b') if ok else None
            b = list(b) if isinstance(b, list) and len(b) == k and all(type(x) is int and x in (-1, 0, 1) for x in b) else [0] * k
            q = m.get('q') if ok else None
            q = list(q) if (isinstance(q, list) and len(q) == k
                            and all(type(x) is int and 0 <= x <= lim for x in q)) else list(leg['sizes'])
            ss = _num(m.get('ss')) if ok else None
            sc = _int(m.get('sc'), 0, 10 ** 9, 0) if ok else 0
            ss = ss if (ss is not None and ss >= 0) else 0.0
            if z is not None:
                if leg['volscale']:
                    ss, sc = ss + sig, sc + 1
                    ratio = min(1.0, (ss / sc) / sig) if sig > 0 else 1.0
                mh, zs = leg['max_hold'], leg['z_stop']
                for i, (e, x) in enumerate(leg['tranches']):
                    prev = st[i]
                    if (b[i] == 1 and z >= -x) or (b[i] == -1 and z <= x):
                        b[i] = 0                    # stopped side re-armed once back at exit level
                    if z <= -e and b[i] != 1:
                        st[i] = 1
                    elif z >= e and b[i] != -1:
                        st[i] = -1
                    elif st[i] == 1 and z >= -x:
                        st[i] = 0
                    elif st[i] == -1 and z <= x:
                        st[i] = 0
                    h[i] = h[i] + 1 if (st[i] != 0 and st[i] == prev) else (1 if st[i] != 0 else 0)
                    if mh is not None and st[i] != 0 and h[i] > int(mh):
                        b[i], st[i], h[i] = st[i], 0, 0         # time stop
                    if zs is not None and st[i] != 0 and -st[i] * z >= float(zs):
                        b[i], st[i], h[i] = st[i], 0, 0         # z loss stop
                    if st[i] != 0 and st[i] != prev:            # tranche (re)opened: fix its size
                        q[i] = (max(1, int(round(leg['sizes'][i] * ratio))) if leg['volscale']
                                else leg['sizes'][i])
            new_m.update(st=st)
            if any(h):
                new_m['h'] = h
            if any(b):
                new_m['b'] = b
            if leg['volscale']:
                new_m.update(q=q, ss=round(ss, 4), sc=sc)
            if z is None:
                target = 0                          # warm-up / reset: never hold unmanaged inventory
            else:
                target = sum(st[i] * q[i] for i in range(k)) * (-1 if leg['flip'] else 1)
            target = max(-lim, min(lim, target))
            delta = target - pos
            if delta > 0:
                qty = min(delta, av, lim - pos)
                return ([Order(sym, int(ba), int(qty))] if qty > 0 else []), new_m
            if delta < 0:
                qty = min(-delta, bv, lim + pos)
                return ([Order(sym, int(bb), -int(qty))] if qty > 0 else []), new_m
            return [], new_m
    return _Namespace(locals())
