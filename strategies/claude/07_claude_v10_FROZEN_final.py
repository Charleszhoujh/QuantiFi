# Module S_quad7_interior8 - LYCHEE voucher cross-strike relative value (smile fit from the OTHER strikes)
# ======================================================================================
def _build_plugin_smile(env):
    Order = env['Order']
    LIMITS = env['LIMITS']
    top = env['top']
    read_memory = env['read_memory']
    original = env['original']
    PEARLS = env['PEARLS']
    pending = env['pending']
    target_order = env['target_order']
    detector = env['detector']
    structure = env['structure']
    wave = env['wave']
    claude_I = env['claude_I']
    """Direction F: LYCHEE vouchers -- cross-strike smile relative value.

Only `datamodel` and the standard library are imported (submission rule).

Model (all from the CURRENT tick's quotes; no history, no timestamps):
  * S = LYCHEE mid; C_k = VOUCHER_k mid.
  * Black-Scholes call with r = 0 written in TOTAL volatility w = sigma*sqrt(T):
        C = S N(d1) - K N(d1 - w),  d1 = (ln(S/K) + w^2/2) / w.
    With r = 0 the price and delta depend on (sigma, T) only through w, so the
    model needs no time-to-expiry and no day index (TTE-free). Optional r > 0
    (sensitivity runs only) enters through an effective strike K*exp(-r*T),
    which is the only place `tte_days` is used.
  * Implied w_k per strike by safeguarded Newton.
  * Smile: least-squares quadratic w(x) = a + b x + c x^2, x = ln(K/S), fitted
    LEAVE-ONE-OUT (target strike excluded) to the other strikes' current w.
    fair_k = BS(S, K, w_fit_k). Alternative smile 'nbr': linear interpolation
    in x between the nearest other strikes (extrapolated at the wings).

Modes (cfg['mode']):
  'take' : H1/H2. Buy at ask levels with fair - price >= thr; sell at bid levels
           with price - fair >= thr; close a long when mid >= fair - exit_band
           (short symmetric). Absolute position per strike <= cap.
  'mm'   : H3. Passive quotes: bid = min(best_bid + 1, floor(fair - mm_edge)),
           ask = max(best_ask - 1, ceil(fair + mm_edge)); never crosses.
  'penny': H3 baseline. bid = best_bid + 1, ask = best_ask - 1 (no model).
  'join' : B0 baseline (official example 1 style). bid = best_bid, ask = best_ask.
Optional LYCHEE delta hedge (cfg['hedge_band'] not None): net exposure
E = sum_k pos_k * N(d1_k) + pos_LYCHEE (positions as of the start of the tick).
If |E| > hedge_band, take LYCHEE at the best level toward E = 0.
"""
    from datamodel import Order
    import json
    import math

    STRIKES = (6800, 7000, 7200, 7300, 7400, 7500, 7600, 7750, 7900, 8100)
    VOUCHERS = tuple(f'VOUCHER_{k}' for k in STRIKES)
    UNDERLYING = 'LYCHEE'
    PRODUCTS = (UNDERLYING,) + VOUCHERS
    LIMIT_V = 50          # official Wiki: 50 per strike
    LIMIT_U = 200         # official Wiki: LYCHEE 200

    DEFAULTS = {
        'mode': 'take',
        'strikes': list(STRIKES),   # strikes this module may trade
        'smile': 'quad',            # 'quad' (LOO quadratic) or 'nbr' (LOO neighbour interp)
        'thr': 3.0,                 # take entry: fair - ask >= thr (price units)
        'exit_band': 0.0,           # close long when mid >= fair - exit_band
        'cap': 50,                  # max |position| per strike (<= 50)
        'mm_edge': 1.0,             # 'mm' mode: minimum quote distance from fair
        'hedge_band': None,         # None = unhedged; else LYCHEE take-hedge band (deltas)
        'r_per_day': 0.0,           # assumption: zero rate (no settlement in the game)
        'tte_days': 8.0,            # only used when r_per_day != 0 (sensitivity runs)
        'min_fit': 4,               # minimum other strikes with valid IV to fit
    }

    INV_SQRT2 = 1.0 / math.sqrt(2.0)
    INV_SQRT2PI = 1.0 / math.sqrt(2.0 * math.pi)
    W_LO, W_HI = 1e-4, 1.0


    def ncdf(x):
        return 0.5 * (1.0 + math.erf(x * INV_SQRT2))


    def bs_call(S, K, w):
        """r = 0 Black-Scholes call in total vol w (K may be a discounted strike)."""
        if w <= 0.0:
            return max(S - K, 0.0)
        d1 = (math.log(S / K) + 0.5 * w * w) / w
        return S * ncdf(d1) - K * ncdf(d1 - w)


    def call_delta(S, K, w):
        if w <= 0.0:
            return 1.0 if S > K else 0.0
        return ncdf((math.log(S / K) + 0.5 * w * w) / w)


    def implied_w(C, S, K, w0=0.055):
        """Total implied vol, or None if C is outside the no-arbitrage band."""
        intrinsic = S - K if S > K else 0.0
        if not (C > intrinsic + 1e-6 and C < S):
            return None
        lo, hi = W_LO, W_HI
        if bs_call(S, K, lo) >= C:
            return None
        if bs_call(S, K, hi) <= C:
            return None
        w = w0
        lnSK = math.log(S / K)
        for _ in range(40):
            d1 = (lnSK + 0.5 * w * w) / w
            diff = S * ncdf(d1) - K * ncdf(d1 - w) - C
            if abs(diff) < 1e-6:
                return w
            if diff > 0:
                hi = w
            else:
                lo = w
            vega = S * math.exp(-0.5 * d1 * d1) * INV_SQRT2PI
            nw = w - diff / vega if vega > 1e-12 else -1.0
            if not (lo < nw < hi):
                nw = 0.5 * (lo + hi)
            w = nw
            if hi - lo < 1e-10:
                return w
        return w


    def _solve3(m, v):
        """Solve 3x3 linear system by Cramer's rule; None if singular."""
        (a, b, c), (d, e, f), (g, h, i) = m
        det = a * (e * i - f * h) - b * (d * i - f * g) + c * (d * h - e * g)
        if abs(det) < 1e-18:
            return None
        p, q, r = v
        x0 = (p * (e * i - f * h) - b * (q * i - f * r) + c * (q * h - e * r)) / det
        x1 = (a * (q * i - f * r) - p * (d * i - f * g) + c * (d * r - q * g)) / det
        x2 = (a * (e * r - q * h) - b * (d * r - q * g) + p * (d * h - e * g)) / det
        return x0, x1, x2


    def loo_quad(xs, ws, min_fit=4):
        """Leave-one-out quadratic fit. xs/ws: lists with None for invalid points.

    Returns list of fitted w at each x (None where not computable)."""
        n = len(xs)
        sums = [0.0] * 5           # sum x^0..x^4
        sy = [0.0] * 3             # sum y, xy, x^2 y
        cnt = 0
        for x, w in zip(xs, ws):
            if w is None:
                continue
            cnt += 1
            x2 = x * x
            sums[0] += 1.0
            sums[1] += x
            sums[2] += x2
            sums[3] += x2 * x
            sums[4] += x2 * x2
            sy[0] += w
            sy[1] += w * x
            sy[2] += w * x2
        out = [None] * n
        for j in range(n):
            x = xs[j]
            if ws[j] is not None:
                k = cnt - 1
                x2 = x * x
                s0, s1, s2, s3, s4 = (sums[0] - 1.0, sums[1] - x, sums[2] - x2,
                                      sums[3] - x2 * x, sums[4] - x2 * x2)
                y0, y1, y2 = sy[0] - ws[j], sy[1] - ws[j] * x, sy[2] - ws[j] * x2
            else:
                k = cnt
                s0, s1, s2, s3, s4 = sums
                y0, y1, y2 = sy
            if k < min_fit:
                continue
            sol = _solve3(((s0, s1, s2), (s1, s2, s3), (s2, s3, s4)), (y0, y1, y2))
            if sol is None:
                continue
            out[j] = sol[0] + sol[1] * x + sol[2] * x * x
        return out


    def loo_nbr(xs, ws, min_fit=4):
        """Leave-one-out linear interpolation between nearest valid other strikes."""
        n = len(xs)
        out = [None] * n
        valid = [i for i in range(n) if ws[i] is not None]
        for j in range(n):
            others = [i for i in valid if i != j]
            if len(others) < max(2, min_fit):
                continue
            left = [i for i in others if xs[i] < xs[j]]
            right = [i for i in others if xs[i] > xs[j]]
            if left and right:
                a, b = left[-1], right[0]
            elif len(right) >= 2:
                a, b = right[0], right[1]
            elif len(left) >= 2:
                a, b = left[-2], left[-1]
            else:
                continue
            xa, xb = xs[a], xs[b]
            if xb == xa:
                continue
            out[j] = ws[a] + (ws[b] - ws[a]) * (xs[j] - xa) / (xb - xa)
        return out


    def _book(depth):
        """(bids desc [(p, v>0)], asks asc [(p, v>0)]) or None if a side is missing."""
        try:
            if depth is None or not depth.buy_orders or not depth.sell_orders:
                return None
            bids = sorted(((p, v) for p, v in depth.buy_orders.items() if v > 0), reverse=True)
            asks = sorted((p, -v) for p, v in depth.sell_orders.items() if v < 0)
            if not bids or not asks or bids[0][0] >= asks[0][0]:
                return None
            return bids, asks
        except (AttributeError, TypeError, ValueError):
            return None


    def model_snapshot(state, cfg):
        """Current-quote model: dict with S, per-strike mid/book/w/fair/delta."""
        ub = _book(state.order_depths.get(UNDERLYING))
        if ub is None:
            return None
        S = (ub[0][0][0] + ub[1][0][0]) / 2.0
        r = float(cfg.get('r_per_day') or 0.0)
        disc = math.exp(-r * float(cfg.get('tte_days') or 0.0)) if r else 1.0
        books, mids, ws, xs, keff = [], [], [], [], []
        for k, sym in zip(STRIKES, VOUCHERS):
            b = _book(state.order_depths.get(sym))
            books.append(b)
            K = k * disc
            keff.append(K)
            xs.append(math.log(K / S))
            if b is None:
                mids.append(None)
                ws.append(None)
                continue
            m = (b[0][0][0] + b[1][0][0]) / 2.0
            mids.append(m)
            ws.append(implied_w(m, S, K))
        fit = (loo_nbr if cfg.get('smile') == 'nbr' else loo_quad)(xs, ws, int(cfg.get('min_fit', 4)))
        fair, delta = [], []
        for j in range(len(STRIKES)):
            fair.append(bs_call(S, keff[j], fit[j]) if fit[j] is not None else None)
            wd = ws[j] if ws[j] is not None else fit[j]
            delta.append(call_delta(S, keff[j], wd) if wd is not None else None)
        return {'S': S, 'ubook': ub, 'books': books, 'mids': mids, 'w': ws, 'wfit': fit,
                'fair': fair, 'delta': delta}


    def _take_orders(sym, book, mid, fair, pos, cfg):
        bids, asks = book
        thr = float(cfg['thr'])
        cap = min(int(cfg['cap']), LIMIT_V)
        ex = float(cfg['exit_band'])
        out = []
        # entry long / cover short (buy side)
        room = cap - pos
        if room > 0 and fair - asks[0][0] >= thr:
            for px, v in asks:
                if fair - px < thr or room <= 0:
                    break
                q = min(v, room)
                out.append(Order(sym, int(px), int(q)))
                room -= q
            return out
        room = cap + pos
        if room > 0 and bids[0][0] - fair >= thr:
            for px, v in bids:
                if px - fair < thr or room <= 0:
                    break
                q = min(v, room)
                out.append(Order(sym, int(px), -int(q)))
                room -= q
            return out
        # exits at the touch
        if pos > 0 and mid >= fair - ex:
            q = min(pos, bids[0][1])
            out.append(Order(sym, int(bids[0][0]), -int(q)))
        elif pos < 0 and mid <= fair + ex:
            q = min(-pos, asks[0][1])
            out.append(Order(sym, int(asks[0][0]), int(q)))
        return out


    def _quote_orders(sym, book, fair, pos, cfg, mode):
        bb, ba = book[0][0][0], book[1][0][0]
        cap = min(int(cfg['cap']), LIMIT_V)
        if mode == 'join':
            bid, ask = bb, ba
        else:
            bid, ask = bb + 1, ba - 1
            if mode == 'mm':
                if fair is None:
                    return []
                e = float(cfg['mm_edge'])
                bid = min(bid, math.floor(fair - e))
                ask = max(ask, math.ceil(fair + e))
            bid = min(bid, ba - 1)
            ask = max(ask, bb + 1)
        out = []
        if bid >= ask:
            return out
        if pos < cap and bid > 0:
            out.append(Order(sym, int(bid), int(cap - pos)))
        if pos > -cap and ask > 0:
            out.append(Order(sym, int(ask), -int(cap + pos)))
        return out


    class Trader:
        def __init__(self, config=None):
            self.cfg = {**DEFAULTS, **(config or {})}

        def run(self, state):
            cfg = self.cfg
            try:
                mem = json.loads(state.traderData) if state.traderData else {}
                if not isinstance(mem, dict):
                    mem = {}
            except (ValueError, TypeError):
                mem = {}
            orders = {}
            pos = state.position or {}
            mode = cfg['mode']
            traded = set(int(k) for k in cfg['strikes'])
            snap = None
            if mode in ('take', 'mm') or cfg.get('hedge_band') is not None:
                snap = model_snapshot(state, cfg)
            for j, (k, sym) in enumerate(zip(STRIKES, VOUCHERS)):
                if k not in traded:
                    continue
                if snap is not None:
                    book, fair, mid = snap['books'][j], snap['fair'][j], snap['mids'][j]
                else:
                    book = _book(state.order_depths.get(sym))
                    fair = None
                    mid = None if book is None else (book[0][0][0] + book[1][0][0]) / 2.0
                if book is None:
                    continue
                p = int(pos.get(sym, 0))
                if mode == 'take':
                    if fair is None:
                        continue
                    o = _take_orders(sym, book, mid, fair, p, cfg)
                else:
                    o = _quote_orders(sym, book, fair, p, cfg, mode)
                if o:
                    orders[sym] = o
            band = cfg.get('hedge_band')
            if band is not None and snap is not None:
                h = self._hedge(snap, pos, float(band))
                if h:
                    orders[UNDERLYING] = h
            # Stateless by design: every quantity is rebuilt from the current quotes.
            return orders, 0, json.dumps({}, separators=(',', ':'))

        @staticmethod
        def _hedge(snap, pos, band):
            D = 0.0
            for j, sym in enumerate(VOUCHERS):
                q = int(pos.get(sym, 0))
                if q:
                    d = snap['delta'][j]
                    if d is None:
                        return []          # cannot value the book: do not hedge blindly
                    D += q * d
            h = int(pos.get(UNDERLYING, 0))
            E = D + h
            if abs(E) <= band:
                return []
            bids, asks = snap['ubook']
            target = int(round(-D))
            target = max(-LIMIT_U, min(LIMIT_U, target))
            need = target - h
            if need > 0:
                q = min(need, asks[0][1], LIMIT_U - h)
                return [Order(UNDERLYING, int(asks[0][0]), int(q))] if q > 0 else []
            if need < 0:
                q = min(-need, bids[0][1], LIMIT_U + h)
                return [Order(UNDERLYING, int(bids[0][0]), -int(q))] if q > 0 else []
            return []


