    def _target(sym, book, mid, fair, position, cfg):
        """Exact original order branch, expressed as an intended target."""
        bids, asks = book
        cap = min(int(cfg['cap']), LIMIT_V)
        if cap - position > 0 and fair - asks[0][0] >= cfg['thr']:
            return cap
        if cap + position > 0 and bids[0][0] - fair >= cfg['thr']:
            return -cap
        if position > 0 and mid >= fair - cfg['exit_band']:
            return 0
        if position < 0 and mid <= fair + cfg['exit_band']:
            return 0
        return position


    def propose(state, memory, config):
        """Exact Claude F valuation/signal; pending-aware common-engine proposals.

    Each target is fitted only from other strikes. The target book sets its
    executable entry/exit price, not the fit for its own fair value. Shared
    pending is supplied by root's portfolio controller. Even an exit to zero
    reserves previous same-direction submissions to prevent duplicate exits.

    Empty pending gives EXACT original source orders. Execution timing, shared
    depth and official-cap enforcement remain the common engine's responsibility.
    """
        cfg = {**DEFAULTS, **config}
        if (cfg['mode'] != 'take' or cfg['smile'] != 'quad' or cfg['thr'] != 7.0
            or cfg['exit_band'] != 0 or cfg['hedge_band'] is not None
            or cfg['r_per_day'] != 0 or cfg['min_fit'] != 4
            or type(cfg['cap']) is not int or cfg['cap'] not in (25, 50)):
            raise ValueError('outside registered source-derived configurations')
        traded = tuple(cfg['strikes'])
        allowed = (STRIKES, (7500,), tuple(k for k in STRIKES if k != 7500),
                   tuple(k for k in STRIKES if k not in (6800,8100)),
                   tuple(k for k in STRIKES if k not in (6800,7500,8100)))
        if traded not in allowed:
            raise ValueError('outside registered traded strike sets')
        snap = model_snapshot(state, cfg)
        if snap is None:
            return {}, {}
        orders = {}
        positions = state.position or {}
        all_pending = getattr(state, 'pending_orders', {})
        for j, (strike, symbol) in enumerate(zip(STRIKES, VOUCHERS)):
            if strike not in traded:
                continue
            book, fair, mid = snap['books'][j], snap['fair'][j], snap['mids'][j]
            if book is None or fair is None:
                continue
            position = positions.get(symbol, 0)
            if type(position) is not int or abs(position) > LIMIT_V:
                raise ValueError('invalid actual voucher position')
            proposed = _take_orders(symbol, book, mid, fair, position, cfg)
            if not proposed:
                continue
            target = _target(symbol, book, mid, fair, position, cfg)
            direction = 1 if target > position else -1
            pending = all_pending.get(symbol, (0, 0))
            if (not isinstance(pending, (list, tuple)) or len(pending) != 2
                or any(type(x) is not int or x < 0 for x in pending)):
                continue
            remaining = max(0, abs(target - position) - pending[0 if direction > 0 else 1])
            clean = []
            for order in proposed:
                if order.quantity * direction <= 0:
                    raise AssertionError('original branch direction inconsistent')
                amount = min(abs(order.quantity), remaining)
                if amount:
                    clean.append(Order(symbol, order.price, direction * amount))
                    remaining -= amount
                if not remaining:
                    break
            if clean:
                orders[symbol] = clean
        return orders, {}
    return _Namespace(locals())
