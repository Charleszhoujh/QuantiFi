# Module H3_frozen_anchor_exit - PEANUT_BUTTER mean reversion, EMA500 anchor frozen at entry
# ======================================================================================
def _build_plugin_pb2(env):
    Order = env['Order']
    LIMITS = env['LIMITS']
    top = env['top']
    read_memory = env['read_memory']
    original = env['original']
    PEARLS = env['PEARLS']
    pending = env['pending']
    target_order = env['target_order']
    detector = env['detector']
    structure = env['structure']
    wave = env['wave']
    claude_I = env['claude_I']
    """Registered PB stage2 mechanisms; strict prior estimators and frozen execution rules."""
    import copy
    import math

    P = 'PEANUT_BUTTER'


    def alpha(h):
        return 1 - .5 ** (1 / float(h))


    def prior_features(m):
        history = m.get('history', [])
        history = history if isinstance(history, list) else []
        history = history[-101:]
        displacement = history[-1] - history[0] if len(history) > 1 else 0.
        travel = sum(abs(y-x) for x, y in zip(history, history[1:]))
        return dict(er=abs(displacement)/travel if travel else 0.,
                    displacement=displacement, turn=m.get('turn', 0.))


    class Estimator(claude_I.Trader):
        def __init__(self, c):
            self.c = c
            leg = dict(zmode='D', anchor_hl=500, sd_hl=1000, warmup=300,
                       size=c['cap'], tranches=c.get('tranches', [[2., 0.]]),
                       max_hold=1000, debias=False)
            super().__init__({'legs': {P: leg}})

        def _z(self, leg, mid, m):
            # The inherited estimator is also the exact phase1 numerical control.
            z, sigma, new, fresh = super()._z(leg, mid, m)
            anchor = m.get('a', mid)
            anchor = anchor if type(anchor) in (int, float) and math.isfinite(anchor) else mid
            residual = mid-anchor
            prior_fast = m.get('fast_v')
            prior_fast = prior_fast if type(prior_fast) in (int, float) and prior_fast >= 0 else None
            variance_mode = self.c.get('variance', 'slow')
            variance = m.get('v')
            if variance_mode != 'slow' and z is not None and prior_fast is not None:
                variance = prior_fast if variance_mode == 'fast' else max(variance, prior_fast)
                sigma = math.sqrt(variance) if variance > 0 else None
                z = residual/sigma if sigma else None
            feature = prior_features(m)
            if self.c.get('adaptive'):
                speed = alpha(500)+(alpha(50)-alpha(500))*feature['er']**2
                new['a'] = round(anchor+speed*residual, 4)
            new['fast_v'] = round(residual**2 if prior_fast is None else
                                  prior_fast+alpha(200)*(residual**2-prior_fast), 4)
            history = m.get('history', [])
            history = history if isinstance(history, list) else []
            change = mid-history[-1] if history else 0.
            new['turn'] = feature['turn']+alpha(5)*(change-feature['turn'])
            new['history'] = (history+[mid])[-101:]
            return z, sigma, new, fresh


    def signal_step(mid, old, c):
        est = Estimator(c)
        leg = est.legs[P]
        z, sigma, estimate, fresh = est._z(leg, mid, old)
        # Standard tranche state remains source-identical to Claude's band rules.
        _, new = est._leg(P, leg, (mid-1, mid+1, 1, 1), 0, old)
        feature = prior_features(old)
        oldst = old.get('st', [0]*len(leg['sizes']))
        if not isinstance(oldst, list) or len(oldst) != len(leg['sizes']):
            oldst = [0]*len(leg['sizes'])
        filtered = []
        exit_reason = None
        if c.get('frozen_exit'):
            # Fixed-entry-anchor exit is a separate preregistered state machine.
            previous = oldst[0] if oldst[0] in (-1, 0, 1) and not fresh else 0
            block = (old.get('b') or [0])[0]
            age = (old.get('h') or [0])[0]
            frozen = old.get('frozen_anchor', old.get('a', mid))
            current = previous
            if z is not None:
                if (block == 1 and z >= 0) or (block == -1 and z <= 0):
                    block = 0
                if previous:
                    age += 1
                    if previous*(mid-frozen) >= 0:
                        current, age, exit_reason = 0, 0, 'frozen_anchor'
                    elif age > 1000:
                        block, current, age, exit_reason = previous, 0, 0, 'timeout'
                elif z <= -2 and block != 1:
                    current, age, frozen = 1, 1, old.get('a', mid)
                elif z >= 2 and block != -1:
                    current, age, frozen = -1, 1, old.get('a', mid)
            else:
                current, age = 0, 0
            new.update(st=[current], h=[age], b=[block], q=[c['cap']], frozen_anchor=frozen)
        elif c.get('gate') and z is not None:
            for i, state in enumerate(new['st']):
                # Only fresh signal activation is gated; open states retain exits.
                if state and state != oldst[i]:
                    blocked = (feature['er'] > c['er_threshold'] and
                               state*feature['displacement'] < 0) if c['gate'] == 'efficiency' else state*feature['turn'] <= 0
                    if blocked:
                        new['st'][i], new['h'][i] = 0, 0
                        filtered.append(i)
        desired = sum(s*q for s, q in zip(new['st'], leg['sizes'])) if z is not None else 0
        diag = dict(z=z, sigma=sigma, fair=old.get('a', mid), prior_n=old.get('n', 0),
                    er=feature['er'], displacement=feature['displacement'], turn=feature['turn'],
                    prior_slow_variance=old.get('v'), prior_fast_variance=old.get('fast_v'),
                    filtered_tranches=filtered, signal_states=new['st'],
                    frozen_anchor=new.get('frozen_anchor'), signal_exit_reason=exit_reason)
        return desired, new, diag


    def propose(state, memory, c):
        m = copy.deepcopy(memory)
        book = top(state.order_depths.get(P))
        if book is None or m.get('timestamp') == state.timestamp:
            return {}, m
        bid, ask, mid, bv, av = book
        old = m.get('signal', {})
        old = old if isinstance(old, dict) else {}
        desired, new, diag = signal_step(mid, old, c)
        q = state.position.get(P, 0)
        held = pending(state, P)
        exiting = m.get('exiting', False) is True
        just_flat = False
        if exiting and q == 0 and not any(held):
            exiting, just_flat = False, True
        if not exiting and not just_flat and (q or any(held)):
            if desired == 0 or q*desired < 0 or (held[0] and desired < 0 and q >= 0) or (held[1] and desired > 0 and q <= 0):
                exiting = True
        target = 0 if exiting or just_flat else desired
        rows = []
        if not just_flat and target != q:
            rows = target_order(state, P, target, ask if target > q else bid,
                                av if target > q else bv)
        action = 'exit' if exiting else ('flat_confirmed' if just_flat else
                 ('entry' if rows and q == 0 and not any(held) else 'rebalance' if rows else 'wait'))
        m.update(timestamp=state.timestamp, signal=new, exiting=exiting,
                 diagnostic=dict(timestamp=state.timestamp, mid=mid, position=q,
                                 pending=list(held), desired=desired, target=target, action=action,
                                 orders=[[o.price, o.quantity] for o in rows], **diag))
        return ({P: rows} if rows else {}), m
    return _Namespace(locals())


